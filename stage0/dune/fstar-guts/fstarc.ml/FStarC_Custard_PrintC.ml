let rec pat_tests__go (sub : (string -> string)) (fs : ((string * FStarC_Custard_Syntax.cty)) list) (ps : (FStarC_Custard_Syntax.pat) list) : ((string) list * ((string * string)) list) =
  (match (fs, ps) with
    | (((f, ft) :: fs1), (p :: ps1)) -> (let tmp = (sub f) in
      let tmp1 = (pat_tests tmp ft p) in
      (match tmp1 with
        | (t1, b1) -> (let tmp2 = ((pat_tests__go sub) fs1 ps1) in
          (match tmp2 with
            | (t2, b2) -> ((FStarC_List.op_At t1 t2), (FStarC_List.op_At b1 b2))
          ))
      ))
    | tmp -> ([], [])
  )

and pat_tests (path : string) (t : FStarC_Custard_Syntax.cty) (p : FStarC_Custard_Syntax.pat) : ((string) list * ((string * string)) list) =
  (match p with
    | FStarC_Custard_Syntax.PWild -> ([], [])
    | (FStarC_Custard_Syntax.PVar (x)) -> ([], ((x, path) :: []))
    | (FStarC_Custard_Syntax.PConst ((FStarC_Custard_Syntax.CString (v)))) when (is_string_ty t) -> (let tmp = (constant (FStarC_Custard_Syntax.CString (v))) in
      let tmp1 = (Prims.strcat tmp ") == 0") in
      let tmp2 = (Prims.strcat ", " tmp1) in
      let tmp3 = (Prims.strcat path tmp2) in
      let tmp4 = (Prims.strcat "strcmp(" tmp3) in
      let tmp5 = (tmp4 :: []) in
      (tmp5, []))
    | (FStarC_Custard_Syntax.PConst (c)) -> (let tmp = (converted_int t t c) in
      (match tmp with
        | (Some (v)) -> (((Prims.strcat path (Prims.strcat " == " v)) :: []), [])
        | None -> (let tmp1 = (constant c) in
          let tmp2 = (Prims.strcat " == " tmp1) in
          let tmp3 = (Prims.strcat path tmp2) in
          let tmp4 = (tmp3 :: []) in
          (tmp4, []))
      ))
    | (FStarC_Custard_Syntax.PTuple (tmp)) -> (reject "an anonymous tuple pattern" ("Tuples reach the backend as FStar.Pervasives.Native.MktupleN." :: []))
    | (FStarC_Custard_Syntax.POr (tmp)) -> (reject "a pattern disjunction" ("Split the branch into one per alternative." :: []))
    | (FStarC_Custard_Syntax.PRecord (tn, fs)) -> (let tmp = (find_type tn) in
      (match tmp with
        | (Some ({ FStarC_Custard_Syntax.dt_name = tmp1; dt_params = tmp2; dt_body = (FStarC_Custard_Syntax.TRecord (fields)); dt_flags = tmp3; _ })) -> (FStarC_List.fold_left (fun tmp4 tmp5 -> (match (tmp4, tmp5) with
            | ((ts, bs), (f, q)) -> (let tmp6 = (FStarC_List.tryFind (fun tmp6 -> (match tmp6 with
                  | (g, tmp7) -> ((=) g f)
                )) fields) in
              let ft = (match tmp6 with
                  | (Some ((tmp7, ft))) -> ft
                  | None -> FStarC_Custard_Syntax.TAny
                ) in
              let tmp7 = (c_var f) in
              let tmp8 = (Prims.strcat "." tmp7) in
              let tmp9 = (Prims.strcat path tmp8) in
              let tmp10 = (pat_tests tmp9 ft q) in
              (match tmp10 with
                | (t1, b1) -> ((FStarC_List.op_At ts t1), (FStarC_List.op_At bs b1))
              ))
          )) ([], []) fs)
        | tmp1 -> (let tmp2 = (FStarC_Custard_Syntax.string_of_name tn) in
          let tmp3 = (Prims.strcat "the record type " tmp2) in
          (reject tmp3 ("It belongs to no record declaration in the program." :: [])))
      ))
    | (FStarC_Custard_Syntax.PCtor (cn, ps)) -> (let tmp = (find_ctor cn) in
      (match tmp with
        | None -> (let tmp1 = (FStarC_Custard_Syntax.string_of_name cn) in
          let tmp2 = (Prims.strcat "the constructor " tmp1) in
          (reject tmp2 ("It belongs to no type declaration in the program." :: [])))
        | (Some ((d, fields))) -> (let tests = (if (single_ctor d) then [] else (let tmp1 = (tag_of path d) in
            let tmp2 = (c_tag cn) in
            let tmp3 = (Prims.strcat " == " tmp2) in
            let tmp4 = (Prims.strcat tmp1 tmp3) in
            (tmp4 :: []))) in
          let sub = (fun f -> (if (single_ctor d) then (let tmp1 = (c_var f) in
            let tmp2 = (Prims.strcat "." tmp1) in
            (Prims.strcat path tmp2)) else (let tmp1 = (arm_sel cn fields f) in
            (Prims.strcat path tmp1)))) in
          let tmp1 = ((pat_tests__go sub) fields ps) in
          (match tmp1 with
            | (t2, b2) -> ((FStarC_List.op_At tests t2), b2)
          ))
      ))
  )

let rec emit_match__trim (emits_nothing : (FStarC_Custard_Syntax.pat -> (FStarC_Custard_Syntax.expr -> bool))) (rbs : ((FStarC_Custard_Syntax.pat * (FStarC_Custard_Syntax.expr) option * FStarC_Custard_Syntax.expr)) list) : ((FStarC_Custard_Syntax.pat * (FStarC_Custard_Syntax.expr) option * FStarC_Custard_Syntax.expr)) list =
  (match rbs with
    | ((p, tmp, b) :: rest) when (emits_nothing p b) -> ((emit_match__trim emits_nothing) rest)
    | tmp -> rbs
  )

let guard_rejected (tmp : unit) : 'a =
  (reject "a pattern guard" ("Rewrite the guard as an 'if' in the branch body." :: []))

let rec emit_match__go (ind : string) (scrut : FStarC_Custard_Syntax.expr) (x : string) (ind' : string) (branch_body : (string -> (FStarC_Custard_Syntax.pat -> (FStarC_Custard_Syntax.expr -> string)))) (all_tested : bool) (first : bool) (brs : ((FStarC_Custard_Syntax.pat * (FStarC_Custard_Syntax.expr) option * FStarC_Custard_Syntax.expr)) list) : string =
  (let last = (fun p b -> (if first then (branch_body ind p b) else (let tmp = (branch_body ind' p b) in
    let tmp1 = (brace ind tmp) in
    let tmp2 = (Prims.strcat "else" tmp1) in
    (Prims.strcat ind tmp2)))) in
  (match brs with
    | [] -> ""
    | ((p, g, b) :: []) when (not all_tested) -> ((if (match g with
        | (Some (v)) -> true
        | tmp -> false
      ) then (guard_rejected ()) else ());
      (last p b))
    | ((p, g, b) :: rest) -> ((if (match g with
        | (Some (v)) -> true
        | tmp -> false
      ) then (guard_rejected ()) else ());
      let tmp = (pat_tests x (scrut).FStarC_Custard_Syntax.ty p) in
      (match tmp with
        | (tests, tmp1) -> (if (match tests with
            | [] -> true
            | tmp2 -> false
          ) then (last p b) else (let tmp2 = (branch_body ind' p b) in
          let tmp3 = (brace ind tmp2) in
          let tmp4 = ((emit_match__go ind scrut x ind' branch_body all_tested) false rest) in
          let tmp5 = (Prims.strcat tmp3 tmp4) in
          let tmp6 = (Prims.strcat ")" tmp5) in
          let tmp7 = (Prims.strcat (FStarC_String.concat " && " tests) tmp6) in
          let tmp8 = (Prims.strcat "if (" tmp7) in
          (Prims.strcat (if first then ind else (Prims.strcat ind "else ")) tmp8)))
      ))
  ))

