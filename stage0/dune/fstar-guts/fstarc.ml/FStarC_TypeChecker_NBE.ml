                (tmp4, q))
            )) args) in
          let tmp3 = (FStarC_Syntax_Util.mk_app head args1) in
          (with_range tmp3))
      ))
    | (FStarC_TypeChecker_NBETerm.Quote (qt, qi)) -> (mk (FStarC_Syntax_Syntax.Tm_quoted (qt, qi)))
    | (FStarC_TypeChecker_NBETerm.Lazy ((FStar_Pervasives.Inl (li)), tmp)) -> (mk (FStarC_Syntax_Syntax.Tm_lazy (li)))
    | (FStarC_TypeChecker_NBETerm.Lazy (tmp, thunk)) -> (let tmp1 = (FStarC_Thunk.force thunk) in
      (readback cfg tmp1))
  ))

