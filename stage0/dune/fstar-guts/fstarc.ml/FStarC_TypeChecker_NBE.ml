and readback (cfg : config) (x : FStarC_TypeChecker_NBETerm.t) : (FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax =
  (let debug_ = (debug cfg) in
  let readback_args = (fun cfg1 args -> (map_rev (fun tmp -> (match tmp with
      | (x1, q) -> (let tmp1 = (readback cfg1 x1) in
        (tmp1, q))
    )) args)) in
  let with_range = (fun t -> { FStarC_Syntax_Syntax.n = (t).FStarC_Syntax_Syntax.n;
      pos = (x).FStarC_TypeChecker_NBETerm.nbe_r;
      hash_code = (t).FStarC_Syntax_Syntax.hash_code }) in
  let mk = (fun t -> (FStarC_Syntax_Syntax.mk t (x).FStarC_TypeChecker_NBETerm.nbe_r)) in
  (debug_ (fun tmp -> (let tmp1 = (FStarC_TypeChecker_NBETerm.t_to_string x) in
  (FStarC_Format.print1 "Readback: %s\n" tmp1))));
  (match (x).FStarC_TypeChecker_NBETerm.nbe_t with
    | (FStarC_TypeChecker_NBETerm.Univ (u)) -> (FStarC_Effect.failwith "Readback of universes should not occur")
    | FStarC_TypeChecker_NBETerm.Unknown -> (FStarC_Syntax_Syntax.mk FStarC_Syntax_Syntax.Tm_unknown (x).FStarC_TypeChecker_NBETerm.nbe_r)
    | (FStarC_TypeChecker_NBETerm.Constant (FStarC_TypeChecker_NBETerm.Unit)) -> (with_range FStarC_Syntax_Syntax.unit_const)
    | (FStarC_TypeChecker_NBETerm.Constant ((FStarC_TypeChecker_NBETerm.Bool (true)))) -> (with_range FStarC_Syntax_Util.exp_true_bool)
    | (FStarC_TypeChecker_NBETerm.Constant ((FStarC_TypeChecker_NBETerm.Bool (false)))) -> (with_range FStarC_Syntax_Util.exp_false_bool)
    | (FStarC_TypeChecker_NBETerm.Constant ((FStarC_TypeChecker_NBETerm.Int (i)))) -> (let tmp = (FStarC_Syntax_Util.exp_int i) in
      (with_range tmp))
    | (FStarC_TypeChecker_NBETerm.Constant ((FStarC_TypeChecker_NBETerm.String (s, r)))) -> (mk (FStarC_Syntax_Syntax.Tm_constant ((FStarC_Const.Const_string (s, r)))))
    | (FStarC_TypeChecker_NBETerm.Constant ((FStarC_TypeChecker_NBETerm.Char (c)))) -> (let tmp = (FStarC_Syntax_Util.exp_char c) in
      (with_range tmp))
    | (FStarC_TypeChecker_NBETerm.Constant ((FStarC_TypeChecker_NBETerm.Range (r)))) -> (FStarC_TypeChecker_Primops_Base.embed_simple FStarC_Syntax_Embeddings.e_range (x).FStarC_TypeChecker_NBETerm.nbe_r r)
    | (FStarC_TypeChecker_NBETerm.Constant ((FStarC_TypeChecker_NBETerm.Real (r)))) -> (FStarC_TypeChecker_Primops_Base.embed_simple FStarC_Syntax_Embeddings.e_real (x).FStarC_TypeChecker_NBETerm.nbe_r r)
    | (FStarC_TypeChecker_NBETerm.Constant ((FStarC_TypeChecker_NBETerm.SConst (c)))) -> (mk (FStarC_Syntax_Syntax.Tm_constant (c)))
    | (FStarC_TypeChecker_NBETerm.Meta (t, m)) -> (let tmp = (readback cfg t) in
      let tmp1 = (FStarC_Thunk.force m) in
      let tmp2 = ({ FStarC_Syntax_Syntax.tm = tmp; meta = tmp1 } : FStarC_Syntax_Syntax.term'__Tm_meta__payload) in
      let tmp3 = (FStarC_Syntax_Syntax.Tm_meta (tmp2)) in
      (mk tmp3))
    | (FStarC_TypeChecker_NBETerm.Type_t (u)) -> (mk (FStarC_Syntax_Syntax.Tm_type (u)))
    | (FStarC_TypeChecker_NBETerm.Lam ({ FStarC_TypeChecker_NBETerm.interp = f; shape = shape; arity = arity; _ })) -> (match shape with
        | (FStarC_TypeChecker_NBETerm.Lam_bs (ctx, binders, rc)) -> (let tmp = (FStarC_List.fold_left (fun tmp b -> (match tmp with
              | (ctx1, binders_rev, accus_rev) -> (let x1 = (b).FStarC_Syntax_Syntax.binder_bv in
                let tmp1 = (translate cfg ctx1 (x1).FStarC_Syntax_Syntax.sort) in
                let tnorm = (readback cfg tmp1) in
                let tmp2 = (FStarC_Syntax_Syntax.freshen_bv x1) in
                let x2 = { FStarC_Syntax_Syntax.ppname = (tmp2).FStarC_Syntax_Syntax.ppname;
                    index = (tmp2).FStarC_Syntax_Syntax.index;
                    sort = tnorm } in
