    | (FStarC_TypeChecker_NBETerm.Accu ((FStarC_TypeChecker_NBETerm.UnreducedLetRec (vars_typs_defns, body, lbs)), args)) -> (let lbs1 = (FStarC_List.map2 (fun tmp lb -> (match tmp with
