              (with_range tmp2))
          ))
        | (FStarC_TypeChecker_NBETerm.Lam_primop (fv, args)) -> (let tmp = (FStarC_Syntax_Syntax.mk (FStarC_Syntax_Syntax.Tm_fvar (fv)) (FStarC_Syntax_Syntax.range_of_fv fv)) in
