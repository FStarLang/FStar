    | (FStarC_TypeChecker_NBETerm.Refinement (f, targ)) -> (if (((cfg).core_cfg).FStarC_TypeChecker_Cfg.steps).FStarC_TypeChecker_Cfg.for_extraction then (let tmp = (targ ()) in
