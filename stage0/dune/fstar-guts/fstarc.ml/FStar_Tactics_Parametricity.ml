let push_fv (f1 : FStarC_Reflection_Types.fv) (f2 : FStarC_Reflection_Types.fv) (s : param_state) : param_state =
  { bvmap = (s).bvmap; fresh = (s).fresh; recs = ((f1, f2) :: (s).recs) }

let app_binders (t : FStarC_Reflection_Types.term) (bs : (FStar_Tactics_NamedView.binder) list) (tmp : (FStarC_Tactics_Types.proofstate ref)) : FStarC_Reflection_Types.term =
  (FStar_Reflection_V2_Derived.mk_e_app t (FStar_List_Tot_Base.map FStar_Tactics_V2_SyntaxCoercions.binder_to_term bs))

let param_ctor (nm_ty : FStarC_Reflection_Types.name) (s : param_state) (c : ((string) list * (FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax)) : ((FStarC_Tactics_Types.proofstate ref) -> ((string) list * (FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax)) =
  (fun ps -> ((match c with
    | (nm, ty) -> (fun ps1 -> (let x = (FStar_Tactics_V2_Derived.cur_module () ps1) in
      let x1 = (last nm ps1) in
      let x2 = (Prims.strcat x1 "_param") in
      let x3 = (x2 :: []) in
      let x4 = (FStar_List_Tot_Base.op_At x x3) in
      let x5 = (FStar_Tactics_V2_SyntaxHelpers.collect_arr_bs ty ps1) in
      ((match x5 with
        | (bs, c1) -> (fun ps2 -> (let tmp = (FStarC_Reflection_V2_Builtins.pack_fv nm) in
          let x6 = (fv_to_tm tmp ps2) in
          let x7 = (app_binders x6 bs ps2) in
          let x8 = (FStar_Tactics_Util.fold_left (fun tmp1 b -> (match tmp1 with
              | (s1, bvs) -> (fun ps3 -> (let x8 = (push_binder b s1 ps3) in
                (match x8 with
                  | (s2, (bx0, bx1, bxr)) -> (s2, (bxr :: (bx1 :: (bx0 :: bvs))))
                )))
            )) (s, []) bs ps2) in
          ((match x8 with
            | (s1, bs1) -> (fun ps3 -> (let x9 = (FStar_List_Tot_Base.rev bs1) in
              let tmp1 = (FStarC_Reflection_V2_Data.is_tot_comp c1) in
              let tmp2 = (if tmp1 then (fun tmp2 -> (c1).FStarC_Reflection_V2_Data.result_typ) else (FStar_Tactics_V2_Derived.fail "param_ctor got a non-tot comp")) in
              let x10 = (tmp2 ps3) in
              let x11 = (param' s1 x10 ps3) in
              let x12 = (replace_by s1 false x7 ps3) in
              let x13 = (replace_by s1 true x7 ps3) in
              let x14 = (x13 :: []) in
              let x15 = (x12 :: x14) in
              let x16 = (FStar_Reflection_V2_Derived.mk_e_app x11 x15) in
              let x17 = (FStar_Tactics_V2_SyntaxHelpers.mk_tot_arr x9 x16 ps3) in
              (x4, x17)))
          ) ps2)))
      ) ps1)))
  ) ps))

let param_inductive (se : FStarC_Reflection_Types.sigelt) (fv0 : FStarC_Reflection_Types.fv) (fv1 : FStarC_Reflection_Types.fv) : ((FStarC_Tactics_Types.proofstate ref) -> FStarC_Reflection_Types.decls) =
  (fun ps -> (let x = (FStar_Tactics_NamedView.inspect_sigelt se ps) in
  ((match x with
    | (FStar_Tactics_NamedView.Sg_Inductive ({ FStar_Tactics_NamedView.nm = nm; univs = univs; params = params; typ = typ; ctors = ctors; _ })) -> (fun ps1 -> (let x1 = (push_fv fv0 fv1 init_param_state) in
      let tmp = (FStarC_Reflection_V2_Builtins.pack_fv nm) in
      let x2 = (fv_to_tm tmp ps1) in
      let x3 = (app_binders x2 params ps1) in
      let x4 = (FStar_Tactics_Util.fold_left (fun tmp1 b -> (match tmp1 with
          | (s, bvs) -> (fun ps2 -> (let x4 = (push_binder b s ps2) in
            (match x4 with
              | (s1, (bx0, bx1, bxr)) -> (s1, (bxr :: (bx1 :: (bx0 :: bvs))))
            )))
        )) (x1, []) params ps1) in
      ((match x4 with
        | (s, param_bs) -> (fun ps2 -> (let x5 = (FStar_List_Tot_Base.rev param_bs) in
          let x6 = (param' s typ ps2) in
          let x7 = (replace_by s false x3 ps2) in
          let x8 = (replace_by s true x3 ps2) in
          let x9 = (x8 :: []) in
          let x10 = (x7 :: x9) in
          let x11 = (FStar_Reflection_V2_Derived.mk_e_app x6 x10) in
          let x12 = (FStar_Tactics_Util.map (param_ctor nm s) ctors ps2) in
          let x13 = (FStar_Tactics_NamedView.Sg_Inductive ((let tmp1 = (FStarC_Reflection_V2_Builtins.inspect_fv fv1) in
            ({ FStar_Tactics_NamedView.nm = tmp1;
              univs = univs;
              params = x5;
              typ = x11;
              ctors = x12 } : FStar_Tactics_NamedView.named_sigelt_view__Sg_Inductive__payload)))) in
          let x14 = (FStar_Tactics_NamedView.pack_sigelt x13 ps2) in
          (x14 :: [])))
      ) ps1)))
    | tmp -> (FStar_Tactics_V2_Derived.fail "")
  ) ps)))

let paramd (nm : string) : ((FStarC_Tactics_Types.proofstate ref) -> FStarC_Reflection_Types.decls) =
  (fun ps -> (let x = (FStar_Tactics_V2_Derived.cur_module () ps) in
  let tmp = (FStarC_Reflection_V2_Builtins.explode_qn nm) in
  let x1 = (last tmp ps) in
  let x2 = (Prims.strcat x1 "_param") in
  let x3 = (x2 :: []) in
  let x4 = (FStar_List_Tot_Base.op_At x x3) in
  let x5 = (FStarC_Reflection_V2_Builtins.implode_qn x4) in
  let tmp1 = (FStarC_Reflection_V2_Builtins.explode_qn nm) in
  let x6 = (FStarC_Reflection_V2_Builtins.pack_fv tmp1) in
  let tmp2 = (FStarC_Reflection_V2_Builtins.explode_qn x5) in
  let x7 = (FStarC_Reflection_V2_Builtins.pack_fv tmp2) in
  let x8 = (FStarC_Tactics_V2_Builtins.top_env () ps) in
  let tmp3 = (FStarC_Reflection_V2_Builtins.explode_qn nm) in
  let x9 = (FStarC_Reflection_V2_Builtins.lookup_typ x8 tmp3) in
  ((match x9 with
    | None -> (FStar_Tactics_V2_Derived.fail "param_letbinding: not found")
    | (Some (se)) -> (fun ps1 -> (let x10 = (FStar_Tactics_NamedView.inspect_sigelt se ps1) in
      ((match x10 with
        | (FStar_Tactics_NamedView.Sg_Let (tmp4)) -> (param_letbinding se x6 x7)
        | (FStar_Tactics_NamedView.Sg_Inductive (tmp4)) -> (param_inductive se x6 x7)
        | tmp4 -> (FStar_Tactics_V2_Derived.fail "paramd: unsupported sigelt")
      ) ps1)))
  ) ps)))

