    | (ETuple (tmp)) -> (for_all_children is_droppable e)
    | (ELet (u__1, u__2, u__3, u__4)) -> (for_all_children is_droppable e)
    | (ESeq (u__1, u__2)) -> (for_all_children is_droppable e)
