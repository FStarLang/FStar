    | (EProj (e1, tmp, tmp1)) -> (e1 :: [])
    | (EDiscrim (e1, tmp)) -> (e1 :: [])
    | (ECoerce (e1, tmp)) -> (e1 :: [])
    | (ECast (e1, tmp)) -> (e1 :: [])
    | (ERaise (e1)) -> (e1 :: [])
    | (EWhile (a, b)) -> (a :: (b :: []))
    | (ETry (a, brs)) -> (let tmp = (FStarC_List.collect branch_children brs) in
