  ))

let scope_mod_as_parsing_data (s : scope_mod) : (FStarC_Parser_Dep.parsing_data_elt) list =
  (match s with
    | (Local_bindings (tmp)) -> []
    | (Rec_binding (tmp)) -> []
    | (Module_abbrev (ma)) -> ((FStarC_Parser_Dep.P_alias ((match ma with (custard_tup, _) -> custard_tup), (match ma with (_, custard_tup) -> custard_tup))) :: [])
    | (Open_module_or_namespace ((l, u__k, u__restrict), tmp)) -> ((FStarC_Parser_Dep.P_open (false, l)) :: [])
    | (Top_level_defs (tmp)) -> []
    | (Record_or_dc (tmp)) -> []
  )

let parsing_data_for_scope (e : env) : (FStarC_Parser_Dep.parsing_data_elt) list =
  (let curmod_scope = (match (e).curmodule with
      | None -> []
      | (Some (m)) -> (namespace_scope_of_module m)
    ) in
  let scope_mods = (match curmod_scope with
      | [] -> (e).scope_mods
      | ((lid, tmp, tmp1) :: []) -> (FStarC_List.filter (fun tmp2 -> (match tmp2 with
          | (Open_module_or_namespace ((lid', tmp3, tmp4), true)) -> (not (FStarC_Ident.lid_equals lid lid'))
          | tmp3 -> true
        )) (e).scope_mods)
    ) in
  (FStarC_List.collect scope_mod_as_parsing_data scope_mods))

