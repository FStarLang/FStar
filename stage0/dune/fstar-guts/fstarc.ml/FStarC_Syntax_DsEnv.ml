    | (Some (({ FStarC_Syntax_Syntax.sigel = (FStarC_Syntax_Syntax.Sig_new_effect (ne)); sigrng = tmp1; sigquals = tmp2; sigmeta = tmp3; sigattrs = tmp4; sigopens_and_abbrevs = tmp5; sigopts = tmp6; _ }, tmp7))) -> (Some (ne))
    | tmp1 -> None
  ))

let open_modules_and_namespaces (env : env) : (FStarC_Ident.lident) list =
  (FStarC_List.filter_map (fun tmp -> (match tmp with
    | (Open_module_or_namespace ((lid, u__info, u__restriction), tmp1)) -> (Some (lid))
    | tmp1 -> None
  )) (env).scope_mods)

let module_abbrevs (env : env) : ((FStarC_Ident.ident * FStarC_Ident.lident)) list =
  (FStarC_List.filter_map (fun tmp -> (match tmp with
    | (Module_abbrev ((l, m))) -> (Some ((l, m)))
    | tmp1 -> None
  )) (env).scope_mods)

let export_interface (m : FStarC_Ident.lident) (env : env) : env =
  (let sigelt_in_m = (fun se -> (match (FStarC_Syntax_Util.lids_of_sigelt se) with
      | (l :: tmp) -> ((=) (FStarC_Ident.nsstr l) (FStarC_Ident.string_of_lid m))
      | tmp -> false
    )) in
  let sm = (sigmap env) in
  let env1 = (pop ()) in
  let keys = (FStarC_SMap.keys sm) in
  let sm' = (sigmap env1) in
  (FStarC_List.iter (fun k -> (let tmp = (FStarC_SMap.try_find sm' k) in
  (match tmp with
    | (Some ((se, true))) when (sigelt_in_m se) -> ((FStarC_SMap.remove sm' k);
      let se1 = (match (se).FStarC_Syntax_Syntax.sigel with
          | (FStarC_Syntax_Syntax.Sig_declare_typ ({ FStarC_Syntax_Syntax.lid = l; us = u; t = t; _ })) -> { FStarC_Syntax_Syntax.sigel = (se).FStarC_Syntax_Syntax.sigel;
              sigrng = (se).FStarC_Syntax_Syntax.sigrng;
              sigquals = (FStarC_Syntax_Syntax.Assumption :: (se).FStarC_Syntax_Syntax.sigquals);
              sigmeta = (se).FStarC_Syntax_Syntax.sigmeta;
              sigattrs = (se).FStarC_Syntax_Syntax.sigattrs;
              sigopens_and_abbrevs = (se).FStarC_Syntax_Syntax.sigopens_and_abbrevs;
              sigopts = (se).FStarC_Syntax_Syntax.sigopts }
          | tmp1 -> se
        ) in
      (FStarC_SMap.add sm' k (se1, false)))
    | tmp1 -> ()
  ))) keys);
  env1)

let with_restored_scope (e : env) (f : (env -> ('u_'a * env))) : ('u_'a * env) =
  (let tmp = (f e) in
  (match tmp with
    | (res, e1) -> (res, { curmodule = (e).curmodule;
        curmonad = (e).curmonad;
        modules = (e1).modules;
        scope_mods = (e).scope_mods;
        iface_scope_mods = (e).iface_scope_mods;
        exported_ids = (e1).exported_ids;
        trans_exported_ids = (e1).trans_exported_ids;
        includes = (e1).includes;
        sigaccum = (e).sigaccum;
        sigmap = (e1).sigmap;
        iface = (e).iface;
        admitted_iface = (e).admitted_iface;
        expect_typ = (e).expect_typ;
        syntax_only = (e1).syntax_only;
        ds_hooks = (e1).ds_hooks;
