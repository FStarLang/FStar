            (FStarC_Format.fmt2 "%s=%s" (FStarC_Ident.string_of_lid l) tmp2))
        )) fields) in
      (FStarC_Format.fmt2 "{%s with %s}" tmp tmp1))
    | (Record (None, fields)) -> (let tmp = (to_string_l " " (fun tmp -> (match tmp with
          | (l, e) -> (let tmp1 = (term_to_string e) in
            (FStarC_Format.fmt2 "%s=%s" (FStarC_Ident.string_of_lid l) tmp1))
        )) fields) in
      (FStarC_Format.fmt1 "{%s}" tmp))
    | (Project (e, l)) -> (let tmp = (term_to_string e) in
      (FStarC_Format.fmt2 "%s.%s" tmp (FStarC_Ident.string_of_lid l)))
    | (Product ([], t)) -> (term_to_string t)
    | (Product ((b :: (hd :: tl)), t)) -> (term_to_string (mk_term (Product ((b :: []), (mk_term (Product ((hd :: tl), t)) (x).range (x).level))) (x).range (x).level))
    | (Product ((b :: []), t)) when ((=) (x).level Type_level) -> (let tmp = (binder_to_string b) in
      let tmp1 = (term_to_string t) in
      (FStarC_Format.fmt2 "%s -> %s" tmp tmp1))
    | (Product ((b :: []), t)) when ((=) (x).level Kind) -> (let tmp = (binder_to_string b) in
      let tmp1 = (term_to_string t) in
      (FStarC_Format.fmt2 "%s => %s" tmp tmp1))
    | (Sum (binders, t)) -> (let tmp = (FStarC_List.map (fun tmp -> (match tmp with
          | (FStar_Pervasives.Inl (b)) -> (binder_to_string b)
          | (FStar_Pervasives.Inr (t1)) -> (term_to_string t1)
        )) (FStarC_List.op_At binders ((FStar_Pervasives.Inr (t)) :: []))) in
      (FStarC_String.concat " & " tmp))
    | (QForall (bs, (tmp, pats), t)) -> (let tmp1 = (to_string_l " " binder_to_string bs) in
      let tmp2 = (to_string_l " \\/ " (to_string_l "; " term_to_string) pats) in
      let tmp3 = (term_to_string t) in
      (FStarC_Format.fmt3 "forall %s.{:pattern %s} %s" tmp1 tmp2 tmp3))
    | (QExists (bs, (tmp, pats), t)) -> (let tmp1 = (to_string_l " " binder_to_string bs) in
      let tmp2 = (to_string_l " \\/ " (to_string_l "; " term_to_string) pats) in
      let tmp3 = (term_to_string t) in
      (FStarC_Format.fmt3 "exists %s.{:pattern %s} %s" tmp1 tmp2 tmp3))
    | (QuantOp (i, bs, (tmp, []), t)) -> (let tmp1 = (to_string_l " " binder_to_string bs) in
      let tmp2 = (term_to_string t) in
      (FStarC_Format.fmt3 "%s %s. %s" (FStarC_Ident.string_of_id i) tmp1 tmp2))
    | (QuantOp (i, bs, (tmp, pats), t)) -> (let tmp1 = (to_string_l " " binder_to_string bs) in
      let tmp2 = (to_string_l " \\/ " (to_string_l "; " term_to_string) pats) in
      let tmp3 = (term_to_string t) in
      (FStarC_Format.fmt4 "%s %s.{:pattern %s} %s" (FStarC_Ident.string_of_id i) tmp1 tmp2 tmp3))
    | (Refine (b, t)) -> (let tmp = (binder_to_string b) in
      let tmp1 = (term_to_string t) in
      (FStarC_Format.fmt2 "%s:{%s}" tmp tmp1))
    | (NamedTyp (x1, t)) -> (let tmp = (term_to_string t) in
      (FStarC_Format.fmt2 "%s:%s" (FStarC_Ident.string_of_id x1) tmp))
    | (Paren (t)) -> (let tmp = (term_to_string t) in
      (FStarC_Format.fmt1 "(%s)" tmp))
    | (Product (bs, t)) -> (let tmp = (FStarC_List.map binder_to_string bs) in
      let tmp1 = (FStarC_String.concat "," tmp) in
      let tmp2 = (term_to_string t) in
      (FStarC_Format.fmt2 "Unidentified product: [%s] %s" tmp1 tmp2))
    | (Discrim (lid)) -> (FStarC_Format.fmt1 "%s?" (FStarC_Ident.string_of_lid lid))
    | (Antiquote (t)) -> (let tmp = (term_to_string t) in
      (FStarC_Format.fmt1 "(`#%s)" tmp))
    | (Quote (t, Static)) -> (let tmp = (term_to_string t) in
      (FStarC_Format.fmt1 "(`(%s))" tmp))
    | (Quote (t, Dynamic)) -> (let tmp = (term_to_string t) in
      (FStarC_Format.fmt1 "quote (%s)" tmp))
    | (VQuote (t)) -> (let tmp = (term_to_string t) in
      (FStarC_Format.fmt1 "`%%%s" tmp))
    | (CalcProof (rel, init, steps)) -> (let tmp = (term_to_string rel) in
      let tmp1 = (term_to_string init) in
      let tmp2 = (FStarC_List.map calc_step_to_string steps) in
      let tmp3 = (FStarC_String.concat " " tmp2) in
      (FStarC_Format.fmt3 "calc (%s) { %s %s }" tmp tmp1 tmp3))
    | (ElimForall (bs, t, vs)) -> (let tmp = (binders_to_string " " bs) in
      let tmp1 = (term_to_string t) in
      let tmp2 = (FStarC_List.map term_to_string vs) in
      let tmp3 = (FStarC_String.concat " " tmp2) in
      (FStarC_Format.fmt3 "_elim_ forall %s. %s using %s" tmp tmp1 tmp3))
    | (ElimExists (bs, p, e)) -> (let tmp = (binders_to_string " " bs) in
      let tmp1 = (term_to_string p) in
      let tmp2 = (term_to_string e) in
      (FStarC_Format.fmt3 "eliminate exists %s. %s\n\\with %s" tmp tmp1 tmp2))
    | (ElimImplies (p, q, e)) -> (let tmp = (term_to_string p) in
      let tmp1 = (term_to_string q) in
      let tmp2 = (term_to_string e) in
      (FStarC_Format.fmt3 "_elim_ %s ==> %s with %s" tmp tmp1 tmp2))
    | (ElimOr (p, q, e, e')) -> (let tmp = (term_to_string p) in
      let tmp1 = (term_to_string q) in
      let tmp2 = (term_to_string e) in
      let tmp3 = (term_to_string e') in
      (FStarC_Format.fmt4 "eliminate %s \\/ %s\n\\with %s\n\\and %s" tmp tmp1 tmp2 tmp3))
    | (ElimAnd (p, q, e)) -> (let tmp = (term_to_string p) in
      let tmp1 = (term_to_string q) in
      let tmp2 = (term_to_string e) in
      (FStarC_Format.fmt3 "eliminate %s /\\ %s\n\\with %s" tmp tmp1 tmp2))
    | (IntroForall (xs, p, e)) -> (let tmp = (binders_to_string " " xs) in
      let tmp1 = (term_to_string p) in
      let tmp2 = (term_to_string e) in
      (FStarC_Format.fmt3 "_intro_ forall %s. %s with %s" tmp tmp1 tmp2))
    | (IntroExists (xs, t, vs, e)) -> (let tmp = (binders_to_string " " xs) in
      let tmp1 = (term_to_string t) in
      let tmp2 = (FStarC_List.map term_to_string vs) in
      let tmp3 = (FStarC_String.concat " " tmp2) in
      let tmp4 = (term_to_string e) in
      (FStarC_Format.fmt4 "_intro_ exists %s. %s using %s with %s" tmp tmp1 tmp3 tmp4))
    | (IntroImplies (p, q, e)) -> (let tmp = (term_to_string p) in
      let tmp1 = (term_to_string q) in
      let tmp2 = (term_to_string e) in
      (FStarC_Format.fmt3 "introduce %s ==> %s with %s" tmp tmp1 tmp2))
    | (IntroOr (b, p, q, r)) -> (let tmp = (term_to_string p) in
      let tmp1 = (term_to_string q) in
      let tmp2 = (term_to_string r) in
      (FStarC_Format.fmt4 "_intro_ %s \\/ %s using %s with %s" tmp tmp1 (if b then "Left" else "Right") tmp2))
    | (IntroAnd (p, q, e1, e2)) -> (let tmp = (term_to_string p) in
      let tmp1 = (term_to_string q) in
      let tmp2 = (term_to_string e1) in
      let tmp3 = (term_to_string e2) in
      (FStarC_Format.fmt4 "_intro_ %s /\\ %s with %s and %s" tmp tmp1 tmp2 tmp3))
    | (ListLiteral (ts)) -> (let tmp = (to_string_l "; " term_to_string ts) in
      (FStarC_Format.fmt1 "[%s]" tmp))
    | (SeqLiteral (ts)) -> (let tmp = (to_string_l "; " term_to_string ts) in
      (FStarC_Format.fmt1 "seq![%s]" tmp))
    | (LitDoc (d)) -> (FStarC_Format.fmt1 "litdoc(%s)" (FStar_Pprint.render d))
    | tmp -> (let tmp1 = (fStarC_Class_Tagged_tag_of__term x) in
      let tmp2 = (Prims.strcat "AST.term_to_string missing case: " tmp1) in
      (FStarC_Effect.failwith tmp2))
  )

