let lookup_term (g : uenv) (t : (FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax) : ((ty_binding, exp_binding) FStar_Pervasives.either * (FStarC_Syntax_Syntax.fv_qual) option) =
  (match (t).FStarC_Syntax_Syntax.n with
    | (FStarC_Syntax_Syntax.Tm_name (x)) -> (let tmp = (lookup_bv g x) in
      (tmp, None))
    | (FStarC_Syntax_Syntax.Tm_fvar (x)) -> (let tmp = (lookup_fv (t).FStarC_Syntax_Syntax.pos g x) in
