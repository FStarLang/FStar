type lookup_res =
  | Found of exp_binding
  | WasErased of FStarC_Range_Type.range
  | NotFound


let lookup_fv_generic (g : uenv) (fv : FStarC_Syntax_Syntax.fv) : lookup_res =
  (let v = (FStarC_Util.find_map (g).env_bindings (fun tmp -> (match tmp with
      | (Fv (fv', t)) when (FStarC_Syntax_Syntax.fv_eq fv fv') -> (Some ((Found (t))))
      | (ErasedFv (fv')) when (FStarC_Syntax_Syntax.fv_eq fv fv') -> (let tmp1 = (FStarC_Syntax_Syntax.fStarC_Class_HasRange_pos__fv fv') in
        let tmp2 = (WasErased (tmp1)) in
        (Some (tmp2)))
      | tmp1 -> None
    ))) in
  (match v with
    | (Some (r)) -> r
    | None -> NotFound
  ))

let fStarC_Class_Show_show__lookup_res (tmp : lookup_res) : string =
  (match tmp with
    | (Found (t)) -> "Found .."
    | (WasErased (r)) -> (let tmp1 = (FStarC_Range_Ops.fStarC_Class_Show_show__range r) in
      (Prims.strcat "WasErased " tmp1))
    | NotFound -> "NotFound"
  )

let lookup_fv (r : FStarC_Range_Type.range) (g : uenv) (fv : FStarC_Syntax_Syntax.fv) : exp_binding =
  (let tmp = (lookup_fv_generic g fv) in
  (match tmp with
    | (Found (t)) -> t
    | res -> (let tmp1 = (FStarC_Syntax_Syntax.fStarC_Class_HasRange_pos__fv fv) in
      let tmp2 = (FStarC_Range_Ops.string_of_range tmp1) in
      let tmp3 = (FStarC_Ident.fStarC_Class_Show_show__lident (fv).FStarC_Syntax_Syntax.fv_name) in
      let tmp4 = (fStarC_Class_Show_show__lookup_res res) in
      let tmp5 = (FStarC_Format.fmt3 "Internal error: (%s) free variable %s not found during extraction (res=%s)\n" tmp2 tmp3 tmp4) in
      (FStarC_Effect.failwith tmp5))
  ))

