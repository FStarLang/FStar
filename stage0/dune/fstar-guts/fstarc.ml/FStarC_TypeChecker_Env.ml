    typeof_well_typed_tot_or_gtot_term = (env).typeof_well_typed_tot_or_gtot_term;
    teq_nosmt_force = (env).teq_nosmt_force;
    subtype_nosmt_force = (env).subtype_nosmt_force;
    qtbl_name_and_index = (env).qtbl_name_and_index;
