  let prog1 = (FStarC_List.map (rn_types fields) prog) in
  let prog2 = (FStarC_List.map (rn_terms fields) prog1) in
  let tmp = (FStarC_List.map (fun tmp -> (match tmp with
      | (n, ti) -> (let tmp1 = (rn_type_info fields ti) in
        (n, tmp1))
    )) infos) in
  (prog2, tmp))

