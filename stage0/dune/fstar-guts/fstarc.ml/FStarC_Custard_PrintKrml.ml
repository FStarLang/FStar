let rec krml_pats (env : kenv) (ps : (FStarC_Custard_Syntax.pat) list) : (kenv * (FStarC_Extraction_KrmlAst.pattern) list) =
  (match ps with
    | [] -> (env, [])
    | (p :: ps1) -> (let tmp = (krml_pat env p) in
      (match tmp with
        | (env1, p1) -> (let tmp1 = (krml_pats env1 ps1) in
          (match tmp1 with
            | (env2, ps2) -> (env2, (p1 :: ps2))
          ))
      ))
  )

and krml_pat (env : kenv) (p : FStarC_Custard_Syntax.pat) : (kenv * FStarC_Extraction_KrmlAst.pattern) =
  (match p with
    | FStarC_Custard_Syntax.PWild -> ((extend env "_"), (FStarC_Extraction_KrmlAst.PVar ((dummy_binder "_"))))
    | (FStarC_Custard_Syntax.PVar (x)) -> ((extend env x), (FStarC_Extraction_KrmlAst.PVar ((dummy_binder x))))
    | (FStarC_Custard_Syntax.PConst (FStarC_Custard_Syntax.CUnit)) -> (env, FStarC_Extraction_KrmlAst.PUnit)
    | (FStarC_Custard_Syntax.PConst ((FStarC_Custard_Syntax.CBool (b)))) -> (env, (FStarC_Extraction_KrmlAst.PBool (b)))
    | (FStarC_Custard_Syntax.PConst ((FStarC_Custard_Syntax.CInt (v, b, None)))) -> (let tmp = (krml_int_lit v b) in
      let tmp1 = (FStarC_Extraction_KrmlAst.CInt, tmp) in
      let tmp2 = (FStarC_Extraction_KrmlAst.PConstant (tmp1)) in
      (env, tmp2))
    | (FStarC_Custard_Syntax.PConst ((FStarC_Custard_Syntax.CInt (v, b, (Some (sw)))))) -> (let tmp = (krml_width sw) in
      let tmp1 = (krml_int_lit v b) in
      let tmp2 = (tmp, tmp1) in
      let tmp3 = (FStarC_Extraction_KrmlAst.PConstant (tmp2)) in
      (env, tmp3))
    | (FStarC_Custard_Syntax.PConst ((FStarC_Custard_Syntax.CChar (c)))) -> (let tmp = (FStarC_Class_Show.fStarC_Class_Show_show__int_4 (FStar_Char.int_of_char c)) in
      let tmp1 = (FStarC_Extraction_KrmlAst.UInt32, tmp) in
      let tmp2 = (FStarC_Extraction_KrmlAst.PConstant (tmp1)) in
      (env, tmp2))
    | (FStarC_Custard_Syntax.PConst ((FStarC_Custard_Syntax.CString (tmp)))) -> (let tmp1 = (FStarC_Options.custard_backend ()) in
      let tmp2 = ((=) tmp1 "KrmlRust") in
      (if tmp2 then (krml_reject_rust "a string pattern" "A flat string match is compiled to a comparison chain using krmllib's __eq__Prims_string, which is C and has no Rust counterpart.") else (krml_reject_c_ok "a string pattern")))
    | (FStarC_Custard_Syntax.PConst ((FStarC_Custard_Syntax.CFloat (u__1, u__2)))) -> (krml_reject_c_ok "a floating-point pattern")
    | (FStarC_Custard_Syntax.PConst (tmp)) -> (krml_reject "this constant pattern")
    | (FStarC_Custard_Syntax.PCtor (n, ps)) when (is_tuple_ctor_name n) -> (let tmp = (krml_pats env ps) in
      (match tmp with
        | (env1, ps1) -> (env1, (FStarC_Extraction_KrmlAst.PTuple (ps1)))
      ))
    | (FStarC_Custard_Syntax.PCtor (n, ps)) -> (let tmp = (krml_pats env ps) in
      (match tmp with
        | (env1, ps1) -> (let tmp1 = (ctor_name n) in
          let tmp2 = (tmp1, ps1) in
          let tmp3 = (FStarC_Extraction_KrmlAst.PCons (tmp2)) in
          (env1, tmp3))
      ))
    | (FStarC_Custard_Syntax.PRecord (tmp, fs)) -> (let tmp1 = (FStarC_List.map Custard_FStar_Pervasives_Native.fStar_Pervasives_Native_snd fs) in
      let tmp2 = (krml_pats env tmp1) in
      (match tmp2 with
        | (env1, ps) -> (let tmp3 = (FStarC_List.map Custard_FStar_Pervasives_Native.fStar_Pervasives_Native_fst fs) in
          let tmp4 = (FStarC_List.zip tmp3 ps) in
          let tmp5 = (FStarC_Extraction_KrmlAst.PRecord (tmp4)) in
          (env1, tmp5))
      ))
    | (FStarC_Custard_Syntax.PTuple (ps)) -> (let tmp = (krml_pats env ps) in
      (match tmp with
        | (env1, ps1) -> (env1, (FStarC_Extraction_KrmlAst.PTuple (ps1)))
      ))
    | (FStarC_Custard_Syntax.POr (tmp)) -> (krml_reject "a pattern disjunction")
  )

