let rec krml_typ (env : kenv) (t : FStarC_Custard_Syntax.cty) : FStarC_Extraction_KrmlAst.typ =
  (match t with
    | FStarC_Custard_Syntax.TUnit -> FStarC_Extraction_KrmlAst.TUnit
    | FStarC_Custard_Syntax.TAny -> FStarC_Extraction_KrmlAst.TAny
    | FStarC_Custard_Syntax.TExn -> FStarC_Extraction_KrmlAst.TAny
    | (FStarC_Custard_Syntax.TInt (u__1, u__2)) -> (let tmp = (krml_width (u__1, u__2)) in
      (FStarC_Extraction_KrmlAst.TInt (tmp)))
    | (FStarC_Custard_Syntax.TFloat (fw)) -> (let tmp = (krml_fwidth fw) in
      (FStarC_Extraction_KrmlAst.TInt (tmp)))
    | (FStarC_Custard_Syntax.TVar (x)) -> (if (env).tvars_any then FStarC_Extraction_KrmlAst.TAny else (let tmp = (find_t env x) in
      (FStarC_Extraction_KrmlAst.TBound (tmp))))
    | (FStarC_Custard_Syntax.TArrow (a, tmp, b)) -> (let tmp1 = (krml_typ env a) in
      let tmp2 = (krml_typ env b) in
      let tmp3 = (tmp1, tmp2) in
      (FStarC_Extraction_KrmlAst.TArrow (tmp3)))
    | (FStarC_Custard_Syntax.TTuple (ts)) -> (let tmp = (FStarC_List.map (krml_typ env) ts) in
      (FStarC_Extraction_KrmlAst.TTuple (tmp)))
    | (FStarC_Custard_Syntax.TBuf (t1)) -> (let tmp = (krml_typ env t1) in
      (FStarC_Extraction_KrmlAst.TBuf (tmp)))
    | (FStarC_Custard_Syntax.TRef (t1)) -> (let tmp = (krml_typ env t1) in
      (FStarC_Extraction_KrmlAst.TBuf (tmp)))
    | (FStarC_Custard_Syntax.TInline (tmp)) -> (FStarC_Effect.failwith "Custard: an inline-field marker reached the karamel backend")
    | (FStarC_Custard_Syntax.TConst (tmp)) -> (FStarC_Errors.fStarC_Errors_raise_error0__list_document FStarC_Errors_Codes.Error_CustardBadTemplateArg ((FStarC_Errors_Msg.text "Custard: an external type with a template target reached the karamel backend.") :: ((FStarC_Errors_Msg.text "A template-id is a C++ construction: [wmma::fragment<matrix_a, 16, 16, 16, half, row_major>] is one type and [wmma::fragment<matrix_b, ...>] another, and neither the OCaml nor the karamel type language has anywhere to put the arguments.  Section 69 is a C-backend feature (--custard_backend C).") :: ((FStarC_Errors_Msg.text "The unparameterized form still works everywhere: a [@@custard_extern] target with no [{0}] placeholder names one target type and its arguments are dropped.") :: []))))
    | (FStarC_Custard_Syntax.TApp (n, args)) when (if (match args with
      | (hd :: tl) -> true
      | tmp -> false
    ) then (let tmp = (!(extern_types)) in
    let tmp1 = (FStarC_Custard_Syntax.string_of_name n) in
    let tmp2 = (FStarC_SMap.try_find tmp tmp1) in
    (match tmp2 with
      | (Some (t1)) -> (let tmp3 = (FStarC_Custard_Syntax.template_of_string t1) in
        (FStarC_Custard_Syntax.is_template tmp3))
      | None -> false
    )) else false) -> (FStarC_Errors.fStarC_Errors_raise_error0__list_document FStarC_Errors_Codes.Error_CustardBadTemplateArg ((FStarC_Errors_Msg.text "Custard: an external type with a template target reached the karamel backend.") :: ((FStarC_Errors_Msg.text "A template-id is a C++ construction: [wmma::fragment<matrix_a, 16, 16, 16, half, row_major>] is one type and [wmma::fragment<matrix_b, ...>] another, and neither the OCaml nor the karamel type language has anywhere to put the arguments.  Section 69 is a C-backend feature (--custard_backend C).") :: ((FStarC_Errors_Msg.text "The unparameterized form still works everywhere: a [@@custard_extern] target with no [{0}] placeholder names one target type and its arguments are dropped.") :: []))))
    | (FStarC_Custard_Syntax.TApp (n, [])) -> (match (prim_type n) with
        | (Some (t1)) -> t1
        | None -> (let tmp = (type_lident_of_name n) in
          (FStarC_Extraction_KrmlAst.TQualified (tmp)))
      )
    | (FStarC_Custard_Syntax.TApp (n, args)) when (is_tuple_type_name n) -> (let tmp = (FStarC_List.map (krml_typ env) args) in
      (FStarC_Extraction_KrmlAst.TTuple (tmp)))
    | (FStarC_Custard_Syntax.TApp (n, args)) -> (let tmp = (type_lident_of_name n) in
      let tmp1 = (FStarC_List.map (krml_typ env) args) in
      let tmp2 = (tmp, tmp1) in
      (FStarC_Extraction_KrmlAst.TApp (tmp2)))
  )

