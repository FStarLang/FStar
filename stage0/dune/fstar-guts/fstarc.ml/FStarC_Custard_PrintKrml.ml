let rec string_match__chain (x : string) (st : FStarC_Extraction_KrmlAst.typ) (env' : kenv) (brs : ((FStarC_Custard_Syntax.pat * (FStarC_Custard_Syntax.expr) option * FStarC_Custard_Syntax.expr)) list) : FStarC_Extraction_KrmlAst.expr =
  (match brs with
    | [] -> (krml_reject "a string match with no catch-all")
    | ((FStarC_Custard_Syntax.PWild, tmp, body) :: tmp1) -> (krml_expr env' body)
    | (((FStarC_Custard_Syntax.PVar (y)), tmp, body) :: tmp1) -> (let yb = { FStarC_Extraction_KrmlAst.name = y; typ = st; mut = false; meta = [] } in
      let tmp2 = (find env' x) in
      let tmp3 = (FStarC_Extraction_KrmlAst.EBound (tmp2)) in
      let tmp4 = (krml_expr (extend env' y) body) in
      let tmp5 = (yb, tmp3, tmp4) in
      (FStarC_Extraction_KrmlAst.ELet (tmp5)))
    | (((FStarC_Custard_Syntax.PConst ((FStarC_Custard_Syntax.CString (v)))), tmp, body) :: rest) -> (let tmp1 = (find env' x) in
      let tmp2 = (FStarC_Extraction_KrmlAst.EBound (tmp1)) in
      let tmp3 = (tmp2 :: ((FStarC_Extraction_KrmlAst.EString (v)) :: [])) in
      let tmp4 = ((FStarC_Extraction_KrmlAst.ETypApp (((FStarC_Extraction_KrmlAst.EOp ((FStarC_Extraction_KrmlAst.Eq, FStarC_Extraction_KrmlAst.Bool))), (st :: [])))), tmp3) in
      let tmp5 = (FStarC_Extraction_KrmlAst.EApp (tmp4)) in
      let tmp6 = (krml_expr env' body) in
      let tmp7 = ((string_match__chain x st env') rest) in
      let tmp8 = (tmp5, tmp6, tmp7) in
      (FStarC_Extraction_KrmlAst.EIfThenElse (tmp8)))
    | tmp -> (krml_reject "a string pattern")
  )

and string_match (env : kenv) (scrut : FStarC_Custard_Syntax.expr) (brs : ((FStarC_Custard_Syntax.pat * (FStarC_Custard_Syntax.expr) option * FStarC_Custard_Syntax.expr)) list) : FStarC_Extraction_KrmlAst.expr =
  (let x = (fresh_local env "scrut") in
  let st = (krml_typ env (scrut).FStarC_Custard_Syntax.ty) in
  let b = { FStarC_Extraction_KrmlAst.name = x; typ = st; mut = false; meta = [] } in
  let env' = (extend env x) in
  let tmp = (krml_expr env scrut) in
  let tmp1 = ((string_match__chain x st env') brs) in
  let tmp2 = (b, tmp, tmp1) in
  (FStarC_Extraction_KrmlAst.ELet (tmp2)))

and krml_branch (env : kenv) (br : (FStarC_Custard_Syntax.pat * (FStarC_Custard_Syntax.expr) option * FStarC_Custard_Syntax.expr)) : (FStarC_Extraction_KrmlAst.pattern * FStarC_Extraction_KrmlAst.expr) =
  (match br with
    | (p, g, body) -> (let tmp = (krml_pat env p) in
      (match tmp with
        | (env', p1) -> (match g with
            | None -> (let tmp1 = (krml_expr env' body) in
              (p1, tmp1))
            | (Some (tmp1)) -> (krml_reject "a pattern guard")
          )
      ))
  )

and krml_expr (env : kenv) (e : FStarC_Custard_Syntax.expr) : FStarC_Extraction_KrmlAst.expr =
  (match (e).FStarC_Custard_Syntax.e with
    | (FStarC_Custard_Syntax.EConst (c)) -> (krml_const c)
    | (FStarC_Custard_Syntax.EVar (x)) -> (let tmp = (find env x) in
      (FStarC_Extraction_KrmlAst.EBound (tmp)))
    | (FStarC_Custard_Syntax.EQual (n, [])) -> (let tmp = (value_lident_of_name n) in
      (FStarC_Extraction_KrmlAst.EQualified (tmp)))
    | (FStarC_Custard_Syntax.EQual (n, tys)) -> (let tmp = (value_lident_of_name n) in
      let tmp1 = (FStarC_Extraction_KrmlAst.EQualified (tmp)) in
      let tmp2 = (FStarC_List.map (krml_typ env) tys) in
      let tmp3 = (tmp1, tmp2) in
      (FStarC_Extraction_KrmlAst.ETypApp (tmp3)))
    | (FStarC_Custard_Syntax.ELet (x, t, e1, e2)) -> (let tmp = (krml_typ env t) in
      let b = { FStarC_Extraction_KrmlAst.name = x;
          typ = tmp;
          mut = false;
          meta = [] } in
      let tmp1 = (krml_expr env e1) in
