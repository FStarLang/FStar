let doc_of_mltydecl (currentModule : string) (decls : (FStarC_Extraction_ML_Syntax.one_mltydecl) list) : string =
  (let for1 = (fun tmp -> (let x = (match (tmp).FStarC_Extraction_ML_Syntax.tydecl_ignored with
        | None -> (tmp).FStarC_Extraction_ML_Syntax.tydecl_name
        | (Some (y)) -> y
      ) in
    let tparams = (FStarC_Extraction_ML_Syntax.ty_param_names (tmp).FStarC_Extraction_ML_Syntax.tydecl_parameters) in
    let tparams1 = (match tparams with
        | [] -> empty
        | (x1 :: []) -> (let tmp1 = (FStarC_Extraction_ML_Util.codegen_fsharp ()) in
          (if tmp1 then (tparens x1) else x1))
        | tmp1 -> (let doc = (FStarC_List.map (fun x1 -> x1) tparams) in
          let tmp2 = (FStarC_Extraction_ML_Util.codegen_fsharp ()) in
          (if tmp2 then (let tmp3 = (combine ", " doc) in
          (tparens tmp3)) else (let tmp3 = (combine ", " doc) in
          (parens tmp3))))
      ) in
    let forbody = (fun body -> (match body with
        | (FStarC_Extraction_ML_Syntax.MLTD_Abbrev (ty)) -> (doc_of_mltype currentModule (min_op_prec, NonAssoc) ty)
        | (FStarC_Extraction_ML_Syntax.MLTD_Record (fields)) -> (let forfield = (fun tmp1 -> (match tmp1 with
              | (name, ty) -> (let ty1 = (doc_of_mltype currentModule (min_op_prec, NonAssoc) ty) in
                (reduce1 (name :: (":" :: (ty1 :: [])))))
            )) in
          let tmp1 = (FStarC_List.map forfield fields) in
          let tmp2 = (combine "; " tmp1) in
          (cbrackets tmp2))
        | (FStarC_Extraction_ML_Syntax.MLTD_DType (ctors)) -> (let forctor = (fun tmp1 -> (match tmp1 with
              | (name, tys) -> (let tmp2 = (FStarC_List.split tys) in
                (match tmp2 with
                  | (u__names, tys1) -> (match tys1 with
                      | [] -> name
                      | tmp3 -> (let tys2 = (FStarC_List.map (doc_of_mltype currentModule (t_prio_tpl, Left)) tys1) in
                        let tys3 = (combine " * " tys2) in
                        (reduce1 (name :: ("of" :: (tys3 :: [])))))
                    )
                ))
            )) in
          let ctors1 = (FStarC_List.map forctor ctors) in
          let ctors2 = (FStarC_List.map (fun d -> (reduce1 ("|" :: (d :: [])))) ctors1) in
          (combine hardline ctors2))
      )) in
    let tmp1 = (FStarC_Extraction_ML_Util.codegen_fsharp ()) in
    let doc = (if tmp1 then (let tmp2 = (ptsym currentModule ([], x)) in
      let tmp3 = (tmp2 :: (tparams1 :: [])) in
      (reduce tmp3)) else (let tmp2 = (ptsym currentModule ([], x)) in
      let tmp3 = (tmp2 :: []) in
      let tmp4 = (tparams1 :: tmp3) in
      (reduce1 tmp4))) in
    (match (tmp).FStarC_Extraction_ML_Syntax.tydecl_defn with
      | None -> doc
      | (Some (body_val)) -> (let body = (forbody body_val) in
        let tmp2 = (FStarC_Extraction_ML_Util.codegen_fsharp ()) in
        let sep = (if tmp2 then (match body_val with
            | (FStarC_Extraction_ML_Syntax.MLTD_DType (tmp3)) -> hardline
            | tmp3 -> break1
          ) else hardline) in
        let tmp3 = (reduce1 (doc :: ("=" :: []))) in
        let tmp4 = (tmp3 :: (body :: [])) in
        (combine sep tmp4))
    ))) in
  let doc = (FStarC_List.map for1 decls) in
  (if (match doc with
    | (hd :: tl) -> true
    | tmp -> false
  ) then (let tmp = (combine " \n and " doc) in
  let tmp1 = (tmp :: []) in
  let tmp2 = ("type" :: tmp1) in
  (reduce1 tmp2)) else ""))

let doc_of_mod1 (currentModule : string) (m : FStarC_Extraction_ML_Syntax.mlmodule1) : string =
  (match (m).FStarC_Extraction_ML_Syntax.mlmodule1_m with
    | (FStarC_Extraction_ML_Syntax.MLM_Exn (x, [])) -> (reduce1 ("exception" :: (x :: [])))
    | (FStarC_Extraction_ML_Syntax.MLM_Exn (x, args)) -> (let args1 = (FStarC_List.map Custard_FStar_Pervasives_Native.fStar_Pervasives_Native_snd args) in
      let args2 = (FStarC_List.map (doc_of_mltype currentModule (min_op_prec, NonAssoc)) args1) in
      let tmp = (combine " * " args2) in
      let args3 = (parens tmp) in
      (reduce1 ("exception" :: (x :: ("of" :: (args3 :: []))))))
    | (FStarC_Extraction_ML_Syntax.MLM_Ty (decls)) -> (doc_of_mltydecl currentModule decls)
    | (FStarC_Extraction_ML_Syntax.MLM_Let ((rec__, lets))) -> (doc_of_lets currentModule (rec__, true, lets))
    | (FStarC_Extraction_ML_Syntax.MLM_Top (e)) -> (let tmp = (doc_of_expr currentModule (min_op_prec, NonAssoc) e) in
      let tmp1 = (tmp :: []) in
      let tmp2 = ("=" :: tmp1) in
      let tmp3 = ("_" :: tmp2) in
      let tmp4 = ("let" :: tmp3) in
      (reduce1 tmp4))
    | (FStarC_Extraction_ML_Syntax.MLM_Loc (loc)) -> (doc_of_loc loc)
  )

let doc_of_modbody (currentModule : string) (m : (FStarC_Extraction_ML_Syntax.mlmodule1) list) : string =
  (let docs = (FStarC_List.map (fun x -> (let doc = (doc_of_mod1 currentModule x) in
    (doc :: ((match (x).FStarC_Extraction_ML_Syntax.mlmodule1_m with
      | (FStarC_Extraction_ML_Syntax.MLM_Loc (tmp)) -> empty
      | tmp -> hardline
    ) :: (hardline :: []))))) m) in
  (reduce (FStarC_List.flatten docs)))

let doc_of_mlmodule_r (fsharp : bool) (mod_ : (((string) list * string) * (((FStarC_Extraction_ML_Syntax.mlsig1) list * (FStarC_Extraction_ML_Syntax.mlmodule1) list)) option)) : string =
  (let p_mod = (fun istop mod1 -> (match mod1 with
      | (mod_name, sigmod) -> (let target_mod_name = (FStarC_Extraction_ML_Util.flatten_mlpath mod_name) in
        let head = (reduce1 (if fsharp then ("module" :: (target_mod_name :: [])) else (if (not istop) then ("module" :: (target_mod_name :: ("=" :: ("struct" :: [])))) else []))) in
        let tail = (if (not istop) then (reduce1 ("end" :: [])) else (reduce1 [])) in
        let doc = (FStarC_Option.map (fun tmp -> (match tmp with
            | (tmp1, m) -> (doc_of_modbody target_mod_name m)
          )) sigmod) in
        (reduce (head :: (hardline :: ((match doc with
          | None -> empty
          | (Some (s)) -> (cat s hardline)
        ) :: ((cat tail hardline) :: []))))))
    )) in
  (p_mod true mod_))

let doc_of_mlmodule (fsharp : bool) (mod_ : (((string) list * string) * (((FStarC_Extraction_ML_Syntax.mlsig1) list * (FStarC_Extraction_ML_Syntax.mlmodule1) list)) option)) : string =
  (doc_of_mlmodule_r fsharp mod_)

