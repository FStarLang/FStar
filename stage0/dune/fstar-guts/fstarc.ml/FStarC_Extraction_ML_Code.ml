and doc_of_uniop (currentModule : string) (p : ((string) list * string)) (e1 : FStarC_Extraction_ML_Syntax.mlexpr) : string =
  (let tmp = (as_uni_op p) in
  let tmp1 = (FStarC_Option.must tmp) in
  (match tmp1 with
    | (tmp2, txt) -> (let e11 = (doc_of_expr currentModule (min_op_prec, NonAssoc) e1) in
      let doc = (reduce1 (txt :: ((parens e11) :: []))) in
      (parens doc))
  ))

and doc_of_branch (currentModule : string) (br : (FStarC_Extraction_ML_Syntax.mlpattern * (FStarC_Extraction_ML_Syntax.mlexpr) option * FStarC_Extraction_ML_Syntax.mlexpr)) : string =
  (match br with
    | (p, cond, e) -> (let case = (match cond with
          | None -> (let tmp = (doc_of_pattern currentModule p) in
            let tmp1 = (tmp :: []) in
            let tmp2 = ("|" :: tmp1) in
            (reduce1 tmp2))
          | (Some (c)) -> (let c1 = (doc_of_expr currentModule (min_op_prec, NonAssoc) c) in
            let tmp = (doc_of_pattern currentModule p) in
            let tmp1 = (tmp :: ("when" :: (c1 :: []))) in
            let tmp2 = ("|" :: tmp1) in
            (reduce1 tmp2))
        ) in
      let tmp = (reduce1 (case :: ("->" :: ("begin" :: [])))) in
      let tmp1 = (FStarC_Extraction_ML_Util.codegen_fsharp ()) in
      let tmp2 = (if tmp1 then "    " else empty) in
      let tmp3 = (doc_of_expr currentModule (min_op_prec, NonAssoc) e) in
      let tmp4 = (tmp3 :: []) in
      let tmp5 = (tmp2 :: tmp4) in
      let tmp6 = (reduce1 tmp5) in
      let tmp7 = (FStarC_Extraction_ML_Util.codegen_fsharp ()) in
      let tmp8 = (if tmp7 then "    " else empty) in
      let tmp9 = (tmp8 :: ("end" :: [])) in
      let tmp10 = (reduce1 tmp9) in
      let tmp11 = (tmp10 :: []) in
      let tmp12 = (tmp6 :: tmp11) in
      let tmp13 = (tmp :: tmp12) in
      (combine hardline tmp13))
  )

and doc_of_expr (currentModule : string) (outer : ((Prims.int * fixity) * assoc)) (e : FStarC_Extraction_ML_Syntax.mlexpr) : string =
  (match (e).FStarC_Extraction_ML_Syntax.expr with
    | (FStarC_Extraction_ML_Syntax.MLE_Coerce (e1, t, t')) -> (let doc = (doc_of_expr currentModule (min_op_prec, NonAssoc) e1) in
      let tmp = (FStarC_Extraction_ML_Util.codegen_fsharp ()) in
      (if tmp then (let tmp1 = (reduce ("Prims.unsafe_coerce " :: (doc :: []))) in
      (parens tmp1)) else (let tmp1 = (reduce ("Obj.magic " :: ((parens doc) :: []))) in
      (parens tmp1))))
    | (FStarC_Extraction_ML_Syntax.MLE_Seq (es)) -> (let docs = (FStarC_List.map (doc_of_expr currentModule (min_op_prec, NonAssoc)) es) in
      let docs1 = (FStarC_List.map (fun d -> (reduce (d :: (";" :: (hardline :: []))))) docs) in
      let tmp = (reduce docs1) in
      (parens tmp))
    | (FStarC_Extraction_ML_Syntax.MLE_Const (c)) -> (string_of_mlconstant c)
    | (FStarC_Extraction_ML_Syntax.MLE_Var (x)) -> x
    | (FStarC_Extraction_ML_Syntax.MLE_Name (path)) -> (ptsym currentModule path)
    | (FStarC_Extraction_ML_Syntax.MLE_Record (path, tmp, fields)) -> (let for1 = (fun tmp1 -> (match tmp1 with
          | (name, e1) -> (let doc = (doc_of_expr currentModule (min_op_prec, NonAssoc) e1) in
            let tmp2 = (ptsym currentModule (path, name)) in
            let tmp3 = (tmp2 :: ("=" :: (doc :: []))) in
            (reduce1 tmp3))
        )) in
      let tmp1 = (FStarC_List.map for1 fields) in
      let tmp2 = (combine "; " tmp1) in
      (cbrackets tmp2))
    | (FStarC_Extraction_ML_Syntax.MLE_CTor (ctor, [])) -> (let tmp = (is_standard_constructor ctor) in
      (if tmp then (let tmp1 = (as_standard_constructor ctor) in
      let tmp2 = (FStarC_Option.must tmp1) in
      (Custard_FStar_Pervasives_Native.fStar_Pervasives_Native_snd tmp2)) else (ptctor currentModule ctor)))
    | (FStarC_Extraction_ML_Syntax.MLE_CTor (ctor, args)) -> (let tmp = (is_standard_constructor ctor) in
      let name = (if tmp then (let tmp1 = (as_standard_constructor ctor) in
        let tmp2 = (FStarC_Option.must tmp1) in
        (Custard_FStar_Pervasives_Native.fStar_Pervasives_Native_snd tmp2)) else (ptctor currentModule ctor)) in
      let args1 = (FStarC_List.map (doc_of_expr currentModule (min_op_prec, NonAssoc)) args) in
      let doc = (match (name, args1) with
          | ("::", (x :: (xs :: []))) -> (reduce ((parens x) :: ("::" :: (xs :: []))))
          | (tmp1, tmp2) -> (let tmp3 = (combine ", " args1) in
            let tmp4 = (parens tmp3) in
            let tmp5 = (tmp4 :: []) in
            let tmp6 = (name :: tmp5) in
            (reduce1 tmp6))
        ) in
      (maybe_paren outer e_app_prio doc))
    | (FStarC_Extraction_ML_Syntax.MLE_Tuple (es)) -> (let docs = (FStarC_List.map (fun x -> (let tmp = (doc_of_expr currentModule (min_op_prec, NonAssoc) x) in
        (parens tmp))) es) in
      let tmp = (combine ", " docs) in
      (parens tmp))
    | (FStarC_Extraction_ML_Syntax.MLE_Let ((rec__, lets), body)) -> (let pre = (if ((<>) (e).FStarC_Extraction_ML_Syntax.loc FStarC_Extraction_ML_Syntax.dummy_loc) then (let tmp = (doc_of_loc (e).FStarC_Extraction_ML_Syntax.loc) in
        let tmp1 = (tmp :: []) in
        let tmp2 = (hardline :: tmp1) in
        (reduce tmp2)) else empty) in
      let doc = (doc_of_lets currentModule (rec__, false, lets)) in
      let body1 = (doc_of_expr currentModule (min_op_prec, NonAssoc) body) in
      let tmp = (reduce1 ("in" :: (body1 :: []))) in
      let tmp1 = (tmp :: []) in
      let tmp2 = (doc :: tmp1) in
      let tmp3 = (pre :: tmp2) in
      let tmp4 = (combine hardline tmp3) in
      (parens tmp4))
    | (FStarC_Extraction_ML_Syntax.MLE_App (e1, args)) -> (match ((e1).FStarC_Extraction_ML_Syntax.expr, args) with
        | ((FStarC_Extraction_ML_Syntax.MLE_Name (p)), ({ FStarC_Extraction_ML_Syntax.expr = (FStarC_Extraction_ML_Syntax.MLE_Fun ((tmp :: []), scrutinee)); mlty = tmp1; loc = tmp2; _ } :: ({ FStarC_Extraction_ML_Syntax.expr = (FStarC_Extraction_ML_Syntax.MLE_Fun (({ FStarC_Extraction_ML_Syntax.mlbinder_name = arg; mlbinder_ty = tmp3; mlbinder_attrs = tmp4; _ } :: []), possible_match)); mlty = tmp5; loc = tmp6; _ } :: []))) when (((=) (FStarC_Extraction_ML_Syntax.string_of_mlpath p) "FStarC.Effect.try_with") || ((=) (FStarC_Extraction_ML_Syntax.string_of_mlpath p) "FStar.All.try_with")) -> (let branches = (match possible_match with
              | { FStarC_Extraction_ML_Syntax.expr = (FStarC_Extraction_ML_Syntax.MLE_Match ({ FStarC_Extraction_ML_Syntax.expr = (FStarC_Extraction_ML_Syntax.MLE_Var (arg')); mlty = tmp7; loc = tmp8; _ }, branches)); mlty = tmp9; loc = tmp10; _ } when ((=) arg arg') -> branches
              | e2 -> ((FStarC_Extraction_ML_Syntax.MLP_Wild, None, e2) :: [])
            ) in
          (doc_of_expr currentModule outer { FStarC_Extraction_ML_Syntax.expr = (FStarC_Extraction_ML_Syntax.MLE_Try (scrutinee, branches));
            mlty = (possible_match).FStarC_Extraction_ML_Syntax.mlty;
            loc = (possible_match).FStarC_Extraction_ML_Syntax.loc }))
        | ((FStarC_Extraction_ML_Syntax.MLE_Name (p)), (e11 :: (e2 :: []))) when (is_bin_op p) -> (doc_of_binop currentModule p e11 e2)
        | ((FStarC_Extraction_ML_Syntax.MLE_App ({ FStarC_Extraction_ML_Syntax.expr = (FStarC_Extraction_ML_Syntax.MLE_Name (p)); mlty = tmp; loc = tmp1; _ }, (unitVal :: []))), (e11 :: (e2 :: []))) when (let tmp2 = (is_bin_op p) in
        (if tmp2 then ((=) unitVal FStarC_Extraction_ML_Syntax.ml_unit) else false)) -> (doc_of_binop currentModule p e11 e2)
        | ((FStarC_Extraction_ML_Syntax.MLE_Name (p)), (e11 :: [])) when (is_uni_op p) -> (doc_of_uniop currentModule p e11)
        | ((FStarC_Extraction_ML_Syntax.MLE_App ({ FStarC_Extraction_ML_Syntax.expr = (FStarC_Extraction_ML_Syntax.MLE_Name (p)); mlty = tmp; loc = tmp1; _ }, (unitVal :: []))), (e11 :: [])) when (let tmp2 = (is_uni_op p) in
        (if tmp2 then ((=) unitVal FStarC_Extraction_ML_Syntax.ml_unit) else false)) -> (doc_of_uniop currentModule p e11)
        | tmp -> (let e2 = (doc_of_expr currentModule (e_app_prio, ILeft) e1) in
          let args1 = (FStarC_List.map (doc_of_expr currentModule (e_app_prio, IRight)) args) in
          let tmp1 = (reduce1 (e2 :: args1)) in
          (parens tmp1))
      )
    | (FStarC_Extraction_ML_Syntax.MLE_Proj (e1, f)) -> (let e2 = (doc_of_expr currentModule (min_op_prec, NonAssoc) e1) in
      let tmp = (FStarC_Extraction_ML_Util.codegen_fsharp ()) in
      (if tmp then (reduce (e2 :: ("." :: ((Custard_FStar_Pervasives_Native.fStar_Pervasives_Native_snd f) :: [])))) else (let tmp1 = (ptsym currentModule f) in
      let tmp2 = (tmp1 :: []) in
      let tmp3 = ("." :: tmp2) in
      let tmp4 = (e2 :: tmp3) in
      (reduce tmp4))))
    | (FStarC_Extraction_ML_Syntax.MLE_Fun (ids, body)) -> (let bvar_annot = (fun x xt -> (let tmp = (FStarC_Extraction_ML_Util.codegen_fsharp ()) in
        (if tmp then (let tmp1 = (match xt with
            | (Some (xxt)) -> (let tmp1 = (doc_of_mltype currentModule outer xxt) in
              let tmp2 = (tmp1 :: []) in
              let tmp3 = (" : " :: tmp2) in
              (reduce1 tmp3))
            | tmp1 -> ""
          ) in
        let tmp2 = (tmp1 :: (")" :: [])) in
        let tmp3 = (x :: tmp2) in
        let tmp4 = ("(" :: tmp3) in
        (reduce1 tmp4)) else x))) in
      let ids1 = (FStarC_List.map (fun tmp -> (bvar_annot (tmp).FStarC_Extraction_ML_Syntax.mlbinder_name (Some ((tmp).FStarC_Extraction_ML_Syntax.mlbinder_ty)))) ids) in
      let body1 = (doc_of_expr currentModule (min_op_prec, NonAssoc) body) in
      let tmp = (reduce1 ids1) in
      let tmp1 = (tmp :: ("->" :: (body1 :: []))) in
      let tmp2 = ("fun" :: tmp1) in
      let doc = (reduce1 tmp2) in
      (parens doc))
    | (FStarC_Extraction_ML_Syntax.MLE_If (cond, e1, None)) -> (let cond1 = (doc_of_expr currentModule (min_op_prec, NonAssoc) cond) in
      let tmp = (reduce1 ("if" :: (cond1 :: ("then" :: ("begin" :: []))))) in
      let tmp1 = (doc_of_expr currentModule (min_op_prec, NonAssoc) e1) in
      let tmp2 = (tmp1 :: ("end" :: [])) in
      let tmp3 = (tmp :: tmp2) in
      let doc = (combine hardline tmp3) in
      (maybe_paren outer e_bin_prio_if doc))
    | (FStarC_Extraction_ML_Syntax.MLE_If (cond, e1, (Some (e2)))) -> (let cond1 = (doc_of_expr currentModule (min_op_prec, NonAssoc) cond) in
      let tmp = (FStarC_Extraction_ML_Util.codegen_fsharp ()) in
      let line_prefix = (if tmp then ("    " :: []) else []) in
      let tmp1 = (FStarC_Extraction_ML_Util.codegen_fsharp ()) in
      let tmp2 = (if tmp1 then (break1 :: []) else []) in
      let tmp3 = (reduce1 ("if" :: (cond1 :: ("then" :: ("begin" :: []))))) in
      let tmp4 = (doc_of_expr currentModule (min_op_prec, NonAssoc) e1) in
      let tmp5 = (tmp4 :: []) in
      let tmp6 = (FStarC_List.op_At line_prefix tmp5) in
      let tmp7 = (reduce1 tmp6) in
      let tmp8 = (reduce1 ("end" :: ("else" :: ("begin" :: [])))) in
      let tmp9 = (tmp8 :: []) in
      let tmp10 = (FStarC_List.op_At line_prefix tmp9) in
      let tmp11 = (reduce1 tmp10) in
      let tmp12 = (doc_of_expr currentModule (min_op_prec, NonAssoc) e2) in
      let tmp13 = (tmp12 :: []) in
      let tmp14 = (FStarC_List.op_At line_prefix tmp13) in
      let tmp15 = (reduce1 tmp14) in
      let tmp16 = (reduce1 (FStarC_List.op_At line_prefix ("end" :: []))) in
      let tmp17 = (tmp16 :: []) in
      let tmp18 = (tmp15 :: tmp17) in
      let tmp19 = (tmp11 :: tmp18) in
      let tmp20 = (tmp7 :: tmp19) in
      let tmp21 = (tmp3 :: tmp20) in
      let tmp22 = (FStarC_List.op_At tmp2 tmp21) in
      let doc = (combine hardline tmp22) in
      (maybe_paren outer e_bin_prio_if doc))
    | (FStarC_Extraction_ML_Syntax.MLE_Match (cond, pats)) -> (let cond1 = (doc_of_expr currentModule (min_op_prec, NonAssoc) cond) in
      let pats1 = (FStarC_List.map (doc_of_branch currentModule) pats) in
      let tmp = (reduce1 ("match" :: ((parens cond1) :: ("with" :: [])))) in
      let doc = (tmp :: pats1) in
      let doc1 = (combine hardline doc) in
      (parens doc1))
    | (FStarC_Extraction_ML_Syntax.MLE_Raise (exn, [])) -> (let tmp = (ptctor currentModule exn) in
      let tmp1 = (tmp :: []) in
      let tmp2 = ("raise" :: tmp1) in
      (reduce1 tmp2))
    | (FStarC_Extraction_ML_Syntax.MLE_Raise (exn, args)) -> (let args1 = (FStarC_List.map (doc_of_expr currentModule (min_op_prec, NonAssoc)) args) in
      let tmp = (ptctor currentModule exn) in
      let tmp1 = (combine ", " args1) in
      let tmp2 = (parens tmp1) in
      let tmp3 = (tmp2 :: []) in
      let tmp4 = (tmp :: tmp3) in
      let tmp5 = ("raise" :: tmp4) in
      (reduce1 tmp5))
    | (FStarC_Extraction_ML_Syntax.MLE_Try (e1, pats)) -> (let tmp = (doc_of_expr currentModule (min_op_prec, NonAssoc) e1) in
      let tmp1 = (FStarC_List.map (doc_of_branch currentModule) pats) in
      let tmp2 = (combine hardline tmp1) in
      let tmp3 = (tmp2 :: []) in
      let tmp4 = ("with" :: tmp3) in
      let tmp5 = (tmp :: tmp4) in
      let tmp6 = ("try" :: tmp5) in
      (combine hardline tmp6))
    | (FStarC_Extraction_ML_Syntax.MLE_TApp (head, ty_args)) -> (doc_of_expr currentModule outer head)
  )

