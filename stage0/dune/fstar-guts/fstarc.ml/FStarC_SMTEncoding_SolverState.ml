        to_flush_rev = (can_give2 :: (hd).to_flush_rev);
        pruning_roots = (hd).pruning_roots })
  ))

let rec flush__aux (s : solver_state) (levels : (decls_at_level) list) : (decls_at_level) list =
  (match levels with
    | [] -> []
    | (level :: levels1) -> (match (level).pruning_roots with
        | (Some (roots)) -> (let hd = (prune_level roots level s) in
          (hd :: levels1))
        | None -> (let tmp = ((flush__aux s) levels1) in
          (level :: tmp))
      )
  )

let flush (s : solver_state) : ((FStarC_SMTEncoding_Term.decl) list * solver_state) =
  (let tmp = (FStarC_Options_Ext.enabled "context_pruning") in
  let s1 = (if tmp then (let tmp1 = ((flush__aux s) (s).levels) in
    { levels = tmp1;
      pending_flushes_rev = (s).pending_flushes_rev;
      using_facts_from = (s).using_facts_from;
      retain_assumptions = (s).retain_assumptions }) else s) in
  let tmp1 = (FStarC_List.collect (fun level -> (level).to_flush_rev) (s1).levels) in
  let tmp2 = (FStarC_List.rev tmp1) in
  let to_flush = (FStarC_List.flatten tmp2) in
  let levels = (FStarC_List.map (fun level -> { pruning_state = (level).pruning_state;
      given_decl_names = (level).given_decl_names;
      all_decls_at_level_rev = (level).all_decls_at_level_rev;
      given_some_decls = ((level).given_some_decls || (match (level).to_flush_rev with
        | (hd :: tl) -> true
        | tmp3 -> false
      ));
      to_flush_rev = [];
      pruning_roots = (level).pruning_roots }) (s1).levels) in
  let s11 = { levels = levels;
      pending_flushes_rev = [];
      using_facts_from = (s1).using_facts_from;
      retain_assumptions = (s1).retain_assumptions } in
  let flushed = (FStar_List_Tot_Base.op_At (FStarC_List.rev (s1).pending_flushes_rev) to_flush) in
  (flushed, s11))

let all_decls (s : solver_state) : (FStarC_SMTEncoding_Term.decl) list =
  (let s1 = (reset (s).using_facts_from s) in
  let tmp = (flush s1) in
  (match tmp with
    | (flushed, tmp1) -> flushed
  ))

let give_lazy (ld : lazy_decls) : (solver_state -> solver_state) =
  (give_aux false (Given_lazy (ld)))

