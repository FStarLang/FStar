let buf_prim (n : Prims.int) (o : FStarC_Custard_Syntax.op) (ef : FStarC_Custard_Syntax.eff) (ret : ((FStarC_Custard_Syntax.cty) list -> ((FStarC_Custard_Syntax.expr) list -> FStarC_Custard_Syntax.cty))) (mk_args : ((FStarC_Custard_Syntax.expr) list -> (FStarC_Custard_Syntax.expr) list)) : rule =
