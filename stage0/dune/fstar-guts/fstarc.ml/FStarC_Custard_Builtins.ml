let exn_rule (id : string) : (rule) option =
  (let force = (fun f -> (match (f).FStarC_Custard_Syntax.e with
      | (FStarC_Custard_Syntax.EFun ((b :: []), body)) -> (FStarC_Custard_Syntax.mk (FStarC_Custard_Syntax.ELet ((b).FStarC_Custard_Syntax.b_name, FStarC_Custard_Syntax.TUnit, FStarC_Custard_Syntax.unit_expr, body)) (body).FStarC_Custard_Syntax.ty (body).FStarC_Custard_Syntax.eff)
      | tmp -> (FStarC_Custard_Syntax.mk (FStarC_Custard_Syntax.EApp (f, (FStarC_Custard_Syntax.unit_expr :: []))) FStarC_Custard_Syntax.TAny FStarC_Custard_Syntax.E_Impure)
    )) in
  (match id with
    | "raise" -> (Some ((Rule_prim ((Prims.parse_int "1"), (fun tmp args -> (match args with
        | (e :: []) -> (FStarC_Custard_Syntax.mk (FStarC_Custard_Syntax.ERaise (e)) FStarC_Custard_Syntax.TAny FStarC_Custard_Syntax.E_Impure)
        | tmp1 -> (FStarC_Effect.failwith "Custard: raise applied to the wrong number of arguments")
      ))))))
    | "try_with" -> (Some ((Rule_prim ((Prims.parse_int "2"), (fun tmp args -> (match args with
        | (f :: (h :: [])) -> (let body = (force f) in
          let branches = (match (h).FStarC_Custard_Syntax.e with
              | (FStarC_Custard_Syntax.EFun ((b :: []), body_h)) -> (match (body_h).FStarC_Custard_Syntax.e with
                  | (FStarC_Custard_Syntax.EMatch (scrut, brs)) -> (match (scrut).FStarC_Custard_Syntax.e with
                      | (FStarC_Custard_Syntax.EVar (x)) when ((=) x (b).FStarC_Custard_Syntax.b_name) -> brs
                      | tmp1 -> []
                    )
                  | tmp1 -> []
                )
              | tmp1 -> []
            ) in
          let branches1 = (if (match branches with
              | (hd :: tl) -> true
              | tmp1 -> false
            ) then branches else (let x = (FStarC_Custard_Syntax.mk (FStarC_Custard_Syntax.EVar (exn_var)) FStarC_Custard_Syntax.TExn FStarC_Custard_Syntax.E_Pure) in
            (((FStarC_Custard_Syntax.PVar (exn_var)), None, (FStarC_Custard_Syntax.mk (FStarC_Custard_Syntax.EApp (h, (x :: []))) (body).FStarC_Custard_Syntax.ty FStarC_Custard_Syntax.E_Impure)) :: []))) in
          (FStarC_Custard_Syntax.mk (FStarC_Custard_Syntax.ETry (body, branches1)) (body).FStarC_Custard_Syntax.ty FStarC_Custard_Syntax.E_Impure))
        | tmp1 -> (FStarC_Effect.failwith "Custard: try_with applied to the wrong number of arguments")
      ))))))
    | "failwith" -> (Some ((Rule_extern ({ x_name = None; x_header = None }))))
    | "exit" -> (Some ((Rule_extern ({ x_name = None; x_header = None }))))
    | tmp -> None
  ))

