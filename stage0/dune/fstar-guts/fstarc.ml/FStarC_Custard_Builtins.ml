  ((lifted) := []);
  ds)

let krml_compat_name (ns : (string) list) (id : string) : ((string) list * string) =
  (match (ns, id) with
    | (("Prims" :: []), "op_Plus") -> (ns, "op_Addition")
    | (("Prims" :: []), "op_Minus") -> (ns, "op_Subtraction")
    | (("Prims" :: []), "op_Tilde_Minus") -> (ns, "op_Minus")
    | (("Prims" :: []), "op_Star") -> (ns, "op_Multiply")
    | (("Prims" :: []), "op_Slash") -> (ns, "op_Division")
    | (("Prims" :: []), "op_Percent") -> (ns, "op_Modulus")
    | (("Prims" :: []), "op_Less") -> (ns, "op_LessThan")
    | (("Prims" :: []), "op_Less_Equals") -> (ns, "op_LessThanOrEqual")
    | (("Prims" :: []), "op_Greater") -> (ns, "op_GreaterThan")
    | (("Prims" :: []), "op_Greater_Equals") -> (ns, "op_GreaterThanOrEqual")
    | (("Pulse" :: ("Lib" :: ("Slice" :: []))), "op_Dot_Lparen_Rparen") -> (ns, "op_Array_Access")
    | (("Pulse" :: ("Lib" :: ("Slice" :: []))), "op_Dot_Lparen_Rparen_Less_Minus") -> (ns, "op_Array_Assignment")
    | tmp -> (ns, id)
  )

let builtin_krml_model_ops : (((string) list * (string) list)) list =
  ((("Pulse" :: ("Lib" :: ("Slice" :: []))), ("from_array" :: ("op_Array_Access" :: ("op_Array_Assignment" :: ("split" :: ("subslice" :: ("copy" :: ("len" :: [])))))))) :: [])

let is_known_krml_model_op (ns : (string) list) (id : string) : bool =
  (let tmp = (FStarC_List.tryFind (fun tmp -> (match tmp with
      | (m, tmp1) -> ((=) m ns)
    )) builtin_krml_model_ops) in
  (match tmp with
    | None -> true
    | (Some ((tmp1, ops))) -> (let tmp2 = (krml_compat_name ns id) in
      (match tmp2 with
        | (tmp3, id1) -> (FStarC_List.existsb (fun o -> ((=) o id1)) ops)
      ))
  ))

