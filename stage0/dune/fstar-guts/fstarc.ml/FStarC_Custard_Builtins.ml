let rec list_literal (x : FStarC_Custard_Syntax.expr) : ((FStarC_Custard_Syntax.expr) list) option =
  (match (x).FStarC_Custard_Syntax.e with
    | (FStarC_Custard_Syntax.ECoerce (e1, tmp)) -> (list_literal e1)
    | (FStarC_Custard_Syntax.ECtor (n, [])) when ((=) (n).FStarC_Custard_Syntax.id "Nil") -> (Some ([]))
    | (FStarC_Custard_Syntax.ECtor (n, (hd :: (tl :: [])))) when ((=) (n).FStarC_Custard_Syntax.id "Cons") -> (let tmp = (list_literal tl) in
      (match tmp with
        | (Some (rest)) -> (Some ((hd :: rest)))
        | None -> None
      ))
    | tmp -> None
  )

let describe_shape (x : FStarC_Custard_Syntax.expr) : string =
  (match (x).FStarC_Custard_Syntax.e with
    | (FStarC_Custard_Syntax.EQual (n, tmp)) -> (let tmp1 = (FStarC_Custard_Syntax.string_of_name n) in
      (Prims.strcat "a reference to " tmp1))
    | (FStarC_Custard_Syntax.EApp ({ FStarC_Custard_Syntax.e = (FStarC_Custard_Syntax.EQual (n, tmp)); ty = tmp1; eff = tmp2; _ }, tmp3)) -> (let tmp4 = (FStarC_Custard_Syntax.string_of_name n) in
      (Prims.strcat "an application of " tmp4))
    | (FStarC_Custard_Syntax.EApp (u__1, u__2)) -> "a function application"
    | (FStarC_Custard_Syntax.EVar (v)) -> (Prims.strcat "the local variable " v)
    | (FStarC_Custard_Syntax.EMatch (u__1, u__2)) -> "a match"
    | (FStarC_Custard_Syntax.EIf (u__1, u__2, u__3)) -> "a conditional"
    | (FStarC_Custard_Syntax.ECtor (n, tmp)) -> (let tmp1 = (FStarC_Custard_Syntax.string_of_name n) in
      let tmp2 = (Prims.strcat tmp1 " application") in
      (Prims.strcat "a " tmp2))
    | tmp -> "not a literal list"
  )

let comment_text (which : string) (role : string) (x : FStarC_Custard_Syntax.expr) : string =
  (let what = (Prims.strcat "Pulse.Lib.Comment." (Prims.strcat which (if ((=) role "") then "" else (Prims.strcat "'s " (Prims.strcat role " argument"))))) in
  (match (x).FStarC_Custard_Syntax.e with
    | (FStarC_Custard_Syntax.EConst ((FStarC_Custard_Syntax.CString (s)))) -> (if (FStarC_Util.contains s "*/") then (FStarC_Errors.fStarC_Errors_raise_error0__list_document FStarC_Errors_Codes.Error_CustardBadComment ((FStarC_Errors_Msg.text (Prims.strcat "Custard: the text given to " (Prims.strcat what " contains */, which would end the comment it is emitted into."))) :: ((FStarC_Errors_Msg.text (Prims.strcat "The text is: " s)) :: []))) else s)
    | tmp -> (let tmp1 = (describe_shape x) in
      let tmp2 = (Prims.strcat tmp1 ".") in
      let tmp3 = (Prims.strcat " has to be a string literal, and after reduction this one is " tmp2) in
      let tmp4 = (Prims.strcat what tmp3) in
      let tmp5 = (Prims.strcat "Custard: " tmp4) in
      let tmp6 = (FStarC_Errors_Msg.text tmp5) in
      let tmp7 = (tmp6 :: ((FStarC_Errors_Msg.text "It becomes a comment in the generated code, so there is nowhere to evaluate it.") :: [])) in
      (FStarC_Errors.fStarC_Errors_raise_error0__list_document FStarC_Errors_Codes.Error_CustardBadComment tmp7))
  ))

