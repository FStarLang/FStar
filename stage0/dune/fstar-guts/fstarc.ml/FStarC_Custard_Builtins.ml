  let tmp2 = (FStarC_Custard_Syntax.EOp ((match tmp1 with (custard_tup, _) -> custard_tup), (match tmp1 with (_, custard_tup) -> custard_tup))) in
  let tmp3 = (ret tys args) in
  (FStarC_Custard_Syntax.mk tmp2 tmp3 ef)))))

