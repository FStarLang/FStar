let elim_tydef_or_decl (env : env_t) (td : (string * (FStarC_Extraction_ML_Syntax.meta) list * (((FStarC_Extraction_ML_Syntax.ty_param) list * FStarC_Extraction_ML_Syntax.mlty), Prims.int) FStar_Pervasives.either)) : (env_t * (string * (FStarC_Extraction_ML_Syntax.meta) list * (((FStarC_Extraction_ML_Syntax.ty_param) list * FStarC_Extraction_ML_Syntax.mlty), Prims.int) FStar_Pervasives.either)) =
