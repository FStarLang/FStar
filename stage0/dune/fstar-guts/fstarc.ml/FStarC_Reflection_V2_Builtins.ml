let subst_comp (s : (FStarC_Syntax_Syntax.subst_elt) list) : ((FStarC_Syntax_Syntax.comp_typ) FStarC_Syntax_Syntax.syntax -> (FStarC_Syntax_Syntax.comp_typ) FStarC_Syntax_Syntax.syntax) =
  (FStarC_Syntax_Subst.subst_comp s)

let compare_bv (x : FStarC_Syntax_Syntax.bv) (y : FStarC_Syntax_Syntax.bv) : FStarC_Order.order =
  (let n = (FStarC_Syntax_Syntax.order_bv x y) in
  (if (Prims.op_Less n (Prims.parse_int "0")) then FStarC_Order.Lt else (if ((=) n (Prims.parse_int "0")) then FStarC_Order.Eq else FStarC_Order.Gt)))

let compare_namedv (x : FStarC_Syntax_Syntax.bv) (y : FStarC_Syntax_Syntax.bv) : FStarC_Order.order =
  (let n = (FStarC_Syntax_Syntax.order_bv x y) in
  (if (Prims.op_Less n (Prims.parse_int "0")) then FStarC_Order.Lt else (if ((=) n (Prims.parse_int "0")) then FStarC_Order.Eq else FStarC_Order.Gt)))

let lookup_attr_ses (attr : (FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax) (env : FStarC_TypeChecker_Env.env) : (FStarC_Syntax_Syntax.sigelt) list =
  (let tmp = (FStarC_Syntax_Subst.compress_subst attr) in
  let tmp1 = (tmp).FStarC_Syntax_Syntax.n in
  (match tmp1 with
    | (FStarC_Syntax_Syntax.Tm_fvar (fv)) -> (FStarC_TypeChecker_Env.lookup_attr env (FStarC_Ident.string_of_lid (FStarC_Syntax_Syntax.lid_of_fv fv)))
    | tmp2 -> []
  ))

let lookup_attr (attr : (FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax) (env : FStarC_TypeChecker_Env.env) : (FStarC_Syntax_Syntax.fv) list =
  (let ses = (lookup_attr_ses attr env) in
  (FStarC_List.concatMap (fun se -> (match (FStarC_Syntax_Util.lid_of_sigelt se) with
    | None -> []
    | (Some (l)) -> ((FStarC_Syntax_Syntax.lid_as_fv l None) :: [])
  )) ses))

let all_defs_in_env (env : FStarC_TypeChecker_Env.env) : (FStarC_Syntax_Syntax.fv) list =
  (let tmp = (FStarC_TypeChecker_Env.lidents env) in
  (FStarC_List.map (fun l -> (FStarC_Syntax_Syntax.lid_as_fv l None)) tmp))

