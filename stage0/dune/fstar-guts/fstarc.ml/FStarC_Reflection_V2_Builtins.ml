  (let tmp = (FStarC_TypeChecker_Env.lidents env) in
  (FStarC_List.concatMap (fun l -> (let ns = (FStarC_List.map FStarC_Ident.string_of_id (FStarC_List.init (FStarC_Ident.ids_of_lid l))) in
  (if ((=) ns modul) then ((FStarC_Syntax_Syntax.lid_as_fv l None) :: []) else []))) tmp))

let bv_eq (bv1 : FStarC_Syntax_Syntax.bv) (bv2 : FStarC_Syntax_Syntax.bv) : bool =
  ((=) (bv1).FStarC_Syntax_Syntax.index (bv2).FStarC_Syntax_Syntax.index)

let eqlist (eq : ('tmp -> ('tmp -> bool))) : (('tmp) list -> (('tmp) list -> bool)) =
  (FStarC_Syntax_Util.eqlist eq)

let univ_eq (u1 : FStarC_Syntax_Syntax.universe) : (FStarC_Syntax_Syntax.universe -> bool) =
  (FStarC_Syntax_Util.eq_univs u1)

let univs_eq (us1 : (FStarC_Syntax_Syntax.universe) list) : ((FStarC_Syntax_Syntax.universe) list -> bool) =
  (eqlist univ_eq us1)

let const_eq (c1 : FStarC_Reflection_V2_Data.vconst) (c2 : FStarC_Reflection_V2_Data.vconst) : bool =
  ((=) c1 c2)

let eqopt (e : ('tmp -> ('tmp -> bool))) (x : ('tmp) option) (y : ('tmp) option) : bool =
  (FStarC_Syntax_Util.eqopt e x y)

let eqprod (e1 : ('tmp -> ('tmp -> bool))) (e2 : ('tmp1 -> ('tmp1 -> bool))) : (('tmp * 'tmp1) -> (('tmp * 'tmp1) -> bool)) =
  (FStarC_Syntax_Util.eqprod e1 e2)

let rec aqual_eq (aq1 : FStarC_Reflection_V2_Data.aqualv) (aq2 : FStarC_Reflection_V2_Data.aqualv) : bool =
  (match (aq1, aq2) with
    | (FStarC_Reflection_V2_Data.Q_Implicit, FStarC_Reflection_V2_Data.Q_Implicit) -> true
    | (FStarC_Reflection_V2_Data.Q_Explicit, FStarC_Reflection_V2_Data.Q_Explicit) -> true
    | ((FStarC_Reflection_V2_Data.Q_Meta (t1)), (FStarC_Reflection_V2_Data.Q_Meta (t2))) -> (term_eq t1 t2)
    | tmp -> false
  )

and arg_eq (arg1 : ((FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax * FStarC_Reflection_V2_Data.aqualv)) (arg2 : ((FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax * FStarC_Reflection_V2_Data.aqualv)) : bool =
  (match arg1 with
    | (a1, aq1) -> (match arg2 with
        | (a2, aq2) -> (let tmp = (term_eq a1 a2) in
          (if tmp then (aqual_eq aq1 aq2) else false))
      )
  )

and binder_eq (b1 : FStarC_Syntax_Syntax.binder) (b2 : FStarC_Syntax_Syntax.binder) : bool =
  (let bview1 = (inspect_binder b1) in
  let bview2 = (inspect_binder b2) in
  let tmp = (term_eq ((bview1 : FStarC_Reflection_V2_Data.binder_view)).FStarC_Reflection_V2_Data.sort ((bview2 : FStarC_Reflection_V2_Data.binder_view)).FStarC_Reflection_V2_Data.sort) in
  let tmp1 = (if tmp then (aqual_eq (bview1).FStarC_Reflection_V2_Data.qual (bview2).FStarC_Reflection_V2_Data.qual) else false) in
  (if tmp1 then (eqlist term_eq (bview1).FStarC_Reflection_V2_Data.attrs (bview2).FStarC_Reflection_V2_Data.attrs) else false))

and decreases_order_eq (d1 : FStarC_Reflection_V2_Data.decreases_order) (d2 : FStarC_Reflection_V2_Data.decreases_order) : bool =
  (match (d1, d2) with
    | ((FStarC_Reflection_V2_Data.Decreases_lex (ts1)), (FStarC_Reflection_V2_Data.Decreases_lex (ts2))) -> (eqlist term_eq ts1 ts2)
    | ((FStarC_Reflection_V2_Data.Decreases_wf (rel1, e1)), (FStarC_Reflection_V2_Data.Decreases_wf (rel2, e2))) -> (let tmp = (term_eq rel1 rel2) in
      (if tmp then (term_eq e1 e2) else false))
    | tmp -> false
  )

and cflag_eq (f1 : FStarC_Reflection_V2_Data.cflag) (f2 : FStarC_Reflection_V2_Data.cflag) : bool =
  (match (f1, f2) with
    | ((FStarC_Reflection_V2_Data.SMTPAT (t1)), (FStarC_Reflection_V2_Data.SMTPAT (t2))) -> (term_eq t1 t2)
    | ((FStarC_Reflection_V2_Data.DECREASES (d1)), (FStarC_Reflection_V2_Data.DECREASES (d2))) -> (decreases_order_eq d1 d2)
    | tmp -> false
  )

and comp_eq (c1 : (FStarC_Syntax_Syntax.comp_typ) FStarC_Syntax_Syntax.syntax) (c2 : (FStarC_Syntax_Syntax.comp_typ) FStarC_Syntax_Syntax.syntax) : bool =
  (let cv1 = (inspect_comp c1) in
  let cv2 = (inspect_comp c2) in
  let tmp = (if ((=) (cv1).FStarC_Reflection_V2_Data.effect_name (cv2).FStarC_Reflection_V2_Data.effect_name) then (term_eq (cv1).FStarC_Reflection_V2_Data.result_typ (cv2).FStarC_Reflection_V2_Data.result_typ) else false) in
  (if tmp then (eqlist cflag_eq (cv1).FStarC_Reflection_V2_Data.flags (cv2).FStarC_Reflection_V2_Data.flags) else false))

and ascription_eq (asc1 : (((FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax, (FStarC_Syntax_Syntax.comp_typ) FStarC_Syntax_Syntax.syntax) FStar_Pervasives.either * ((FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax) option * bool)) (asc2 : (((FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax, (FStarC_Syntax_Syntax.comp_typ) FStarC_Syntax_Syntax.syntax) FStar_Pervasives.either * ((FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax) option * bool)) : bool =
  (match asc1 with
    | (a1, topt1, eq1) -> (match asc2 with
        | (a2, topt2, eq2) -> (let tmp = (match (a1, a2) with
              | ((FStar_Pervasives.Inl (t1)), (FStar_Pervasives.Inl (t2))) -> (term_eq t1 t2)
              | ((FStar_Pervasives.Inr (c1)), (FStar_Pervasives.Inr (c2))) -> (comp_eq c1 c2)
            ) in
          let tmp1 = (if tmp then (eqopt term_eq topt1 topt2) else false) in
          (if tmp1 then ((=) eq1 eq2) else false))
      )
  )

and match_ret_asc_eq (a1 : (FStarC_Syntax_Syntax.binder * (((FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax, (FStarC_Syntax_Syntax.comp_typ) FStarC_Syntax_Syntax.syntax) FStar_Pervasives.either * ((FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax) option * bool))) : ((FStarC_Syntax_Syntax.binder * (((FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax, (FStarC_Syntax_Syntax.comp_typ) FStarC_Syntax_Syntax.syntax) FStar_Pervasives.either * ((FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax) option * bool)) -> bool) =
  (eqprod binder_eq ascription_eq a1)

and pattern_eq (p1 : FStarC_Reflection_V2_Data.pattern) (p2 : FStarC_Reflection_V2_Data.pattern) : bool =
  (match (p1, p2) with
    | ((FStarC_Reflection_V2_Data.Pat_Constant (c1)), (FStarC_Reflection_V2_Data.Pat_Constant (c2))) -> (const_eq c1 c2)
    | ((FStarC_Reflection_V2_Data.Pat_Cons (fv1, us1, subpats1)), (FStarC_Reflection_V2_Data.Pat_Cons (fv2, us2, subpats2))) -> (let tmp = (if (FStarC_Syntax_Syntax.fv_eq fv1 fv2) then (eqopt (eqlist univ_eq) us1 us2) else false) in
      (if tmp then (eqlist (eqprod pattern_eq (fun b1 b2 -> ((=) b1 b2))) subpats1 subpats2) else false))
    | ((FStarC_Reflection_V2_Data.Pat_Var (tmp, tmp1)), (FStarC_Reflection_V2_Data.Pat_Var (tmp2, tmp3))) -> true
    | ((FStarC_Reflection_V2_Data.Pat_Dot_Term (topt1)), (FStarC_Reflection_V2_Data.Pat_Dot_Term (topt2))) -> (eqopt term_eq topt1 topt2)
    | tmp -> false
  )

and branch_eq (c1 : (FStarC_Reflection_V2_Data.pattern * (FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax)) : ((FStarC_Reflection_V2_Data.pattern * (FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax) -> bool) =
  (eqprod pattern_eq term_eq c1)

and term_eq (t1 : (FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax) (t2 : (FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax) : bool =
  (let tmp = (inspect_ln t1) in
  let tmp1 = (inspect_ln t2) in
  let tmp2 = (tmp, tmp1) in
  (match tmp2 with
    | ((FStarC_Reflection_V2_Data.Tv_Var (bv1)), (FStarC_Reflection_V2_Data.Tv_Var (bv2))) -> (bv_eq bv1 bv2)
    | ((FStarC_Reflection_V2_Data.Tv_BVar (bv1)), (FStarC_Reflection_V2_Data.Tv_BVar (bv2))) -> (bv_eq bv1 bv2)
    | ((FStarC_Reflection_V2_Data.Tv_FVar (fv1)), (FStarC_Reflection_V2_Data.Tv_FVar (fv2))) -> (FStarC_Syntax_Syntax.fv_eq fv1 fv2)
    | ((FStarC_Reflection_V2_Data.Tv_UInst (fv1, us1)), (FStarC_Reflection_V2_Data.Tv_UInst (fv2, us2))) -> (if (FStarC_Syntax_Syntax.fv_eq fv1 fv2) then (univs_eq us1 us2) else false)
    | ((FStarC_Reflection_V2_Data.Tv_App (h1, arg1)), (FStarC_Reflection_V2_Data.Tv_App (h2, arg2))) -> (let tmp3 = (term_eq h1 h2) in
      (if tmp3 then (arg_eq arg1 arg2) else false))
    | ((FStarC_Reflection_V2_Data.Tv_Abs (b1, t11)), (FStarC_Reflection_V2_Data.Tv_Abs (b2, t21))) -> (let tmp3 = (binder_eq b1 b2) in
      (if tmp3 then (term_eq t11 t21) else false))
    | ((FStarC_Reflection_V2_Data.Tv_Arrow (b1, c1)), (FStarC_Reflection_V2_Data.Tv_Arrow (b2, c2))) -> (let tmp3 = (binder_eq b1 b2) in
      (if tmp3 then (comp_eq c1 c2) else false))
    | ((FStarC_Reflection_V2_Data.Tv_Type (u1)), (FStarC_Reflection_V2_Data.Tv_Type (u2))) -> (univ_eq u1 u2)
    | ((FStarC_Reflection_V2_Data.Tv_Refine (b1, t11)), (FStarC_Reflection_V2_Data.Tv_Refine (b2, t21))) -> (let tmp3 = (term_eq ((b1).FStarC_Syntax_Syntax.binder_bv).FStarC_Syntax_Syntax.sort ((b2).FStarC_Syntax_Syntax.binder_bv).FStarC_Syntax_Syntax.sort) in
      (if tmp3 then (term_eq t11 t21) else false))
    | ((FStarC_Reflection_V2_Data.Tv_Const (c1)), (FStarC_Reflection_V2_Data.Tv_Const (c2))) -> (const_eq c1 c2)
    | ((FStarC_Reflection_V2_Data.Tv_Uvar (n1, uv1)), (FStarC_Reflection_V2_Data.Tv_Uvar (n2, uv2))) -> ((=) n1 n2)
    | ((FStarC_Reflection_V2_Data.Tv_Let (r1, ats1, b1, m1, n1)), (FStarC_Reflection_V2_Data.Tv_Let (r2, ats2, b2, m2, n2))) -> (let tmp3 = (if ((=) r1 r2) then (eqlist term_eq ats1 ats2) else false) in
      let tmp4 = (if tmp3 then (binder_eq b1 b2) else false) in
      let tmp5 = (if tmp4 then (term_eq m1 m2) else false) in
      (if tmp5 then (term_eq n1 n2) else false))
    | ((FStarC_Reflection_V2_Data.Tv_Match (h1, an1, brs1)), (FStarC_Reflection_V2_Data.Tv_Match (h2, an2, brs2))) -> (let tmp3 = (term_eq h1 h2) in
      let tmp4 = (if tmp3 then (eqopt match_ret_asc_eq an1 an2) else false) in
      (if tmp4 then (eqlist branch_eq brs1 brs2) else false))
    | ((FStarC_Reflection_V2_Data.Tv_AscribedT (e1, t11, topt1, eq1)), (FStarC_Reflection_V2_Data.Tv_AscribedT (e2, t21, topt2, eq2))) -> (let tmp3 = (term_eq e1 e2) in
      let tmp4 = (if tmp3 then (term_eq t11 t21) else false) in
      let tmp5 = (if tmp4 then (eqopt term_eq topt1 topt2) else false) in
      (if tmp5 then ((=) eq1 eq2) else false))
    | ((FStarC_Reflection_V2_Data.Tv_AscribedC (e1, c1, topt1, eq1)), (FStarC_Reflection_V2_Data.Tv_AscribedC (e2, c2, topt2, eq2))) -> (let tmp3 = (term_eq e1 e2) in
      let tmp4 = (if tmp3 then (comp_eq c1 c2) else false) in
      let tmp5 = (if tmp4 then (eqopt term_eq topt1 topt2) else false) in
      (if tmp5 then ((=) eq1 eq2) else false))
    | (FStarC_Reflection_V2_Data.Tv_Unknown, FStarC_Reflection_V2_Data.Tv_Unknown) -> true
    | tmp3 -> false
  ))

