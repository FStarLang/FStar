let rd_to_syntax_qual (tmp : FStarC_Reflection_V2_Data.qualifier) : FStarC_Syntax_Syntax.qualifier =
  (match tmp with
    | FStarC_Reflection_V2_Data.Assumption -> FStarC_Syntax_Syntax.Assumption
    | FStarC_Reflection_V2_Data.New -> FStarC_Syntax_Syntax.New
    | FStarC_Reflection_V2_Data.Private -> FStarC_Syntax_Syntax.Private
    | FStarC_Reflection_V2_Data.Unfold_for_unification_and_vcgen -> FStarC_Syntax_Syntax.Unfold_for_unification_and_vcgen
    | FStarC_Reflection_V2_Data.Visible_default -> FStarC_Syntax_Syntax.Visible_default
    | FStarC_Reflection_V2_Data.Irreducible -> FStarC_Syntax_Syntax.Irreducible
    | FStarC_Reflection_V2_Data.Inline_for_extraction -> FStarC_Syntax_Syntax.Inline_for_extraction
    | FStarC_Reflection_V2_Data.NoExtract -> FStarC_Syntax_Syntax.NoExtract
    | FStarC_Reflection_V2_Data.Noeq -> FStarC_Syntax_Syntax.Noeq
    | FStarC_Reflection_V2_Data.Unopteq -> FStarC_Syntax_Syntax.Unopteq
    | FStarC_Reflection_V2_Data.TotalEffect -> FStarC_Syntax_Syntax.TotalEffect
    | FStarC_Reflection_V2_Data.Logic -> FStarC_Syntax_Syntax.Logic
    | FStarC_Reflection_V2_Data.Reifiable -> FStarC_Syntax_Syntax.Reifiable
    | (FStarC_Reflection_V2_Data.Reflectable (l)) -> (let tmp1 = (FStarC_Ident.lid_of_path l FStarC_Range_Type.dummyRange) in
      (FStarC_Syntax_Syntax.Reflectable (tmp1)))
    | (FStarC_Reflection_V2_Data.Discriminator (l)) -> (let tmp1 = (FStarC_Ident.lid_of_path l FStarC_Range_Type.dummyRange) in
      (FStarC_Syntax_Syntax.Discriminator (tmp1)))
    | (FStarC_Reflection_V2_Data.Projector (l, i)) -> (let tmp1 = (FStarC_Ident.lid_of_path l FStarC_Range_Type.dummyRange) in
      let tmp2 = (tmp1, i) in
      (FStarC_Syntax_Syntax.Projector ((match tmp2 with (custard_tup, _) -> custard_tup), (match tmp2 with (_, custard_tup) -> custard_tup))))
    | (FStarC_Reflection_V2_Data.RecordType (l1, l2)) -> (FStarC_Syntax_Syntax.RecordType (l1, l2))
    | (FStarC_Reflection_V2_Data.RecordConstructor (l1, l2)) -> (FStarC_Syntax_Syntax.RecordConstructor (l1, l2))
    | (FStarC_Reflection_V2_Data.Action (l)) -> (let tmp1 = (FStarC_Ident.lid_of_path l FStarC_Range_Type.dummyRange) in
      (FStarC_Syntax_Syntax.Action (tmp1)))
    | FStarC_Reflection_V2_Data.ExceptionConstructor -> FStarC_Syntax_Syntax.ExceptionConstructor
    | FStarC_Reflection_V2_Data.HasMaskedEffect -> FStarC_Syntax_Syntax.HasMaskedEffect
    | FStarC_Reflection_V2_Data.Effect -> FStarC_Syntax_Syntax.Effect
    | FStarC_Reflection_V2_Data.OnlyName -> FStarC_Syntax_Syntax.OnlyName
  )

let set_sigelt_quals (quals : (FStarC_Reflection_V2_Data.qualifier) list) (se : FStarC_Syntax_Syntax.sigelt) : FStarC_Syntax_Syntax.sigelt =
  (let tmp = (FStarC_List.map rd_to_syntax_qual quals) in
  { FStarC_Syntax_Syntax.sigel = (se).FStarC_Syntax_Syntax.sigel;
    sigrng = (se).FStarC_Syntax_Syntax.sigrng;
    sigquals = tmp;
    sigmeta = (se).FStarC_Syntax_Syntax.sigmeta;
    sigattrs = (se).FStarC_Syntax_Syntax.sigattrs;
    sigopens_and_abbrevs = (se).FStarC_Syntax_Syntax.sigopens_and_abbrevs;
    sigopts = (se).FStarC_Syntax_Syntax.sigopts })

let subst_term (s : (FStarC_Syntax_Syntax.subst_elt) list) : ((FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax -> (FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax) =
