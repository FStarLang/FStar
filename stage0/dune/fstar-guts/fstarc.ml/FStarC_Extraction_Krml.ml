let translate_constant (c : FStarC_Extraction_ML_Syntax.mlconstant) : FStarC_Extraction_KrmlAst.expr =
  (match c with
    | FStarC_Extraction_ML_Syntax.MLC_Unit -> FStarC_Extraction_KrmlAst.EUnit
    | (FStarC_Extraction_ML_Syntax.MLC_Bool (b)) -> (FStarC_Extraction_KrmlAst.EBool (b))
    | (FStarC_Extraction_ML_Syntax.MLC_String (s)) -> (let tmp = (FStarC_Util.for_some (fun c1 -> ((=) c1 (FStar_Char.char_of_int (Prims.parse_int "0")))) (FStar_String.list_of_string s)) in
      (if tmp then (FStarC_Effect.failwith (FStarC_Format.fmt1 "Refusing to translate a string literal that contains a null character: %s" s)) else ());
      (FStarC_Extraction_KrmlAst.EString (s)))
    | (FStarC_Extraction_ML_Syntax.MLC_Char (c1)) -> (let i = (FStarC_Util.int_of_char c1) in
      let s = (FStarC_Class_Show.fStarC_Class_Show_show__int i) in
      let c2 = (FStarC_Extraction_KrmlAst.EConstant ((FStarC_Extraction_KrmlAst.CInt, s))) in
      let char_of_int = (FStarC_Extraction_KrmlAst.EQualified ((("FStar" :: ("Char" :: [])), "char_of_int"))) in
      (FStarC_Extraction_KrmlAst.EApp ((char_of_int, (c2 :: [])))))
    | (FStarC_Extraction_ML_Syntax.MLC_Int (s, (Some ((sg, wd))))) -> (let tmp = (translate_width (Some ((sg, wd)))) in
      let tmp1 = (tmp, s) in
      (FStarC_Extraction_KrmlAst.EConstant (tmp1)))
    | (FStarC_Extraction_ML_Syntax.MLC_Float (tmp)) -> (FStarC_Effect.failwith "todo: translate_expr [MLC_Float]")
    | (FStarC_Extraction_ML_Syntax.MLC_Int (s, None)) -> (FStarC_Extraction_KrmlAst.EConstant ((FStarC_Extraction_KrmlAst.CInt, s)))
  )

