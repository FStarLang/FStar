let rec translate_pat (env : env) (p : FStarC_Extraction_ML_Syntax.mlpattern) : (env * FStarC_Extraction_KrmlAst.pattern) =
  (match p with
    | (FStarC_Extraction_ML_Syntax.MLP_Const (FStarC_Extraction_ML_Syntax.MLC_Unit)) -> (env, FStarC_Extraction_KrmlAst.PUnit)
    | (FStarC_Extraction_ML_Syntax.MLP_Const ((FStarC_Extraction_ML_Syntax.MLC_Bool (b)))) -> (env, (FStarC_Extraction_KrmlAst.PBool (b)))
    | (FStarC_Extraction_ML_Syntax.MLP_Const ((FStarC_Extraction_ML_Syntax.MLC_Int (s, sw)))) -> (let tmp = (translate_width sw) in
      let tmp1 = (tmp, s) in
      let tmp2 = (FStarC_Extraction_KrmlAst.PConstant (tmp1)) in
      (env, tmp2))
    | (FStarC_Extraction_ML_Syntax.MLP_Var (name)) -> (let env1 = (extend env name) in
      (env1, (FStarC_Extraction_KrmlAst.PVar ({ FStarC_Extraction_KrmlAst.name = name;
        typ = FStarC_Extraction_KrmlAst.TAny;
        mut = false;
        meta = [] }))))
    | FStarC_Extraction_ML_Syntax.MLP_Wild -> (let env1 = (extend env "_") in
      (env1, (FStarC_Extraction_KrmlAst.PVar ({ FStarC_Extraction_KrmlAst.name = "_";
        typ = FStarC_Extraction_KrmlAst.TAny;
        mut = false;
        meta = [] }))))
    | (FStarC_Extraction_ML_Syntax.MLP_CTor ((tmp, cons), ps)) -> (let tmp1 = (FStarC_List.fold_left (fun tmp1 p1 -> (match tmp1 with
          | (env1, acc) -> (let tmp2 = (translate_pat env1 p1) in
            (match tmp2 with
              | (env2, p2) -> (env2, (p2 :: acc))
            ))
        )) (env, []) ps) in
      (match tmp1 with
        | (env1, ps1) -> (env1, (FStarC_Extraction_KrmlAst.PCons ((cons, (FStarC_List.rev ps1)))))
      ))
    | (FStarC_Extraction_ML_Syntax.MLP_Record (tmp, ps)) -> (let tmp1 = (FStarC_List.fold_left (fun tmp1 tmp2 -> (match (tmp1, tmp2) with
          | ((env1, acc), (field, p1)) -> (let tmp3 = (translate_pat env1 p1) in
            (match tmp3 with
              | (env2, p2) -> (env2, ((field, p2) :: acc))
            ))
        )) (env, []) ps) in
      (match tmp1 with
        | (env1, ps1) -> (env1, (FStarC_Extraction_KrmlAst.PRecord ((FStarC_List.rev ps1))))
      ))
    | (FStarC_Extraction_ML_Syntax.MLP_Tuple (ps)) -> (let tmp = (FStarC_List.fold_left (fun tmp p1 -> (match tmp with
          | (env1, acc) -> (let tmp1 = (translate_pat env1 p1) in
            (match tmp1 with
              | (env2, p2) -> (env2, (p2 :: acc))
            ))
        )) (env, []) ps) in
      (match tmp with
