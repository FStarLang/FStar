        | (pats1, sub1) -> ({ FStarC_Syntax_Syntax.v = (FStarC_Syntax_Syntax.Pat_cons (fv, us_opt1, (FStarC_List.rev pats1)));
            p = (p).FStarC_Syntax_Syntax.p }, sub1)
      ))
    | (FStarC_Syntax_Syntax.Pat_var (x)) -> (let tmp = (FStarC_Syntax_Syntax.freshen_bv x) in
      let tmp1 = (subst sub (x).FStarC_Syntax_Syntax.sort) in
      let x' = { FStarC_Syntax_Syntax.ppname = (tmp).FStarC_Syntax_Syntax.ppname;
          index = (tmp).FStarC_Syntax_Syntax.index;
          sort = tmp1 } in
      let tmp2 = (shift_subst (Prims.parse_int "1") sub) in
      let sub1 = ((FStarC_Syntax_Syntax.DB ((Prims.parse_int "0"), x')) :: tmp2) in
      ({ FStarC_Syntax_Syntax.v = (FStarC_Syntax_Syntax.Pat_var (x'));
        p = (p).FStarC_Syntax_Syntax.p }, sub1))
    | (FStarC_Syntax_Syntax.Pat_dot_term (eopt)) -> (let eopt1 = (FStarC_Option.map (subst sub) eopt) in
      ({ FStarC_Syntax_Syntax.v = (FStarC_Syntax_Syntax.Pat_dot_term (eopt1));
        p = (p).FStarC_Syntax_Syntax.p }, sub))
  )

