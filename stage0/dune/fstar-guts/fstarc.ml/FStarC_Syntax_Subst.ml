  (match bs with
    | [] -> []
    | (b :: tl) -> (let tmp = (b).FStarC_Syntax_Syntax.binder_bv in
      let tmp1 = (subst s ((b).FStarC_Syntax_Syntax.binder_bv).FStarC_Syntax_Syntax.sort) in
