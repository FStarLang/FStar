      | (FStarC_Syntax_Syntax.Sig_let ({ FStarC_Syntax_Syntax.lbs = lbs; lids = tmp; _ })) -> (let tmp1 = (FStarC_List.map (fun lb -> { FStarC_Syntax_Syntax.lbname = (lb).FStarC_Syntax_Syntax.lbname;
