and term_eq (t1 : t) (t2 : t) : bool =
  (match ((t1).nbe_t, (t2).nbe_t) with
    | ((Lam ({ interp = interp1; shape = tmp; arity = arity1; _ })), (Lam ({ interp = interp2; shape = tmp1; arity = arity2; _ }))) -> (((=) interp1 interp2) && ((=) arity1 arity2))
    | ((Accu (a1, as1)), (Accu (a2, as2))) -> (atom_eq a1 a2)
    | ((Construct (fv1, us1, args1)), (Construct (fv2, us2, args2))) -> (let tmp = (if ((=) fv1 fv2) then (FStarC_Syntax_Util.eq_univs_list us1 us2) else false) in
      (if tmp then (args_eq args1 args2) else false))
    | ((FV (fv1, us1, args1)), (FV (fv2, us2, args2))) -> (let tmp = (if ((=) fv1 fv2) then (FStarC_Syntax_Util.eq_univs_list us1 us2) else false) in
      (if tmp then (args_eq args1 args2) else false))
    | ((Constant (c1)), (Constant (c2))) -> ((=) c1 c2)
    | ((Type_t (u1)), (Type_t (u2))) -> ((=) u1 u2)
    | ((Univ (u1)), (Univ (u2))) -> ((=) u1 u2)
    | ((Refinement (r1, t11)), (Refinement (r2, t21))) -> (let x = (FStarC_Syntax_Syntax.new_bv None FStarC_Syntax_Syntax.t_unit) in
