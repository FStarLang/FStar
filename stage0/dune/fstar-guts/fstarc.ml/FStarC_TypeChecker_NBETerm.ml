      (if tmp4 then (let tmp5 = (r1 (mkAccuVar x)) in
      let tmp6 = (r2 (mkAccuVar x)) in
      (term_eq tmp5 tmp6)) else false))
    | (Unknown, Unknown) -> true
    | (tmp, tmp1) -> false
  )

