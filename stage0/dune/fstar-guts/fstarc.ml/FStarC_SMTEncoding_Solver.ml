let ask_config (settings : query_settings) (goals : (goal_state) list) : (goal_state) list =
  (let tmp = (quake_bounds ()) in
  (match tmp with
    | (lo, hi) -> (let decided = (fun gst -> (let tmp1 = (FStarC_Options.quake_keep ()) in
        let tmp2 = (not tmp1) in
        (if tmp2 then ((Prims.op_Greater_Equals (gst).gs_nsuccess lo) || (Prims.op_Greater (gst).gs_nfailure (Prims.op_Minus hi lo))) else false))) in
      ((ask_config__rounds settings decided) hi goals []))
  ))

let rec ask_configs (configs : (query_settings) list) (goals : (goal_state) list) : (goal_state) list =
  (let tmp = (quake_bounds ()) in
  (match tmp with
    | (lo, tmp1) -> (match configs with
        | [] -> goals
        | (cfg :: configs1) -> (let goals1 = (ask_config cfg goals) in
          let failed = (FStarC_List.filter (fun gst -> (Prims.op_Less (gst).gs_nsuccess lo)) goals1) in
          (match (failed, configs1) with
            | ([], tmp2) -> []
            | (tmp2, []) -> failed
            | tmp2 -> (let tmp3 = (FStarC_List.map (fun gst -> { gs_goal = (gst).gs_goal;
                  gs_nsuccess = (Prims.parse_int "0");
                  gs_nfailure = (Prims.parse_int "0");
                  gs_errors = (gst).gs_errors }) failed) in
              (ask_configs configs1 tmp3))
          ))
      )
  ))

let mk_answer (failed : (goal_state) list) : answer =
  (let tmp = (quake_bounds ()) in
  (match tmp with
