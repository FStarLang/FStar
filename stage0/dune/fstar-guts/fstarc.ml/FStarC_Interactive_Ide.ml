let run_query (st : FStarC_Interactive_Ide_Types.repl_state) (q : FStarC_Interactive_Ide_Types.query) : ((FStarC_Interactive_Ide_Types.query_status * (FStarC_Json.json) list) * (FStarC_Interactive_Ide_Types.repl_state, Prims.int) FStar_Pervasives.either) =
  (match (q).FStarC_Interactive_Ide_Types.qq with
    | FStarC_Interactive_Ide_Types.Exit -> (as_json_list (run_exit st))
    | FStarC_Interactive_Ide_Types.DescribeProtocol -> (as_json_list (run_describe_protocol st))
    | FStarC_Interactive_Ide_Types.DescribeRepl -> (let tmp = (run_describe_repl st) in
      (as_json_list tmp))
    | (FStarC_Interactive_Ide_Types.GenericError (message)) -> (as_json_list (run_generic_error st message))
    | (FStarC_Interactive_Ide_Types.ProtocolViolation (query)) -> (as_json_list (run_protocol_violation st query))
    | (FStarC_Interactive_Ide_Types.Segment (c)) -> (let tmp = (run_segment st c) in
      (as_json_list tmp))
    | (FStarC_Interactive_Ide_Types.VfsAdd (fname, contents)) -> (let tmp = (run_vfs_add st fname contents) in
      (as_json_list tmp))
    | (FStarC_Interactive_Ide_Types.Push (pquery)) -> (let tmp = (run_push st pquery) in
      (as_json_list tmp))
    | (FStarC_Interactive_Ide_Types.PushPartialCheckedFile (decl_name)) -> (let tmp = (run_load_partial_file st decl_name) in
      (as_json_list tmp))
    | FStarC_Interactive_Ide_Types.Pop -> (let tmp = (run_pop st) in
      (as_json_list tmp))
    | (FStarC_Interactive_Ide_Types.FullBuffer (code, full_kind, with_symbols)) -> ((write_full_buffer_fragment_progress FStarC_Interactive_Incremental.FullBufferStarted);
      let tmp = (FStarC_Interactive_Incremental.run_full_buffer st (q).FStarC_Interactive_Ide_Types.qid code full_kind with_symbols write_full_buffer_fragment_progress) in
      (match tmp with
        | (queries, issues) -> ((FStarC_List.iter (write_response (q).FStarC_Interactive_Ide_Types.qid FStarC_Interactive_Ide_Types.QueryOK) issues);
          let tmp1 = (!(validate_and_run_query_ref)) in
          let res = (fold_query tmp1 queries st) in
          (write_full_buffer_fragment_progress FStarC_Interactive_Incremental.FullBufferFinished);
          res)
      ))
    | (FStarC_Interactive_Ide_Types.AutoComplete (search_term, context)) -> (let tmp = (run_autocomplete st search_term context) in
      (as_json_list tmp))
    | (FStarC_Interactive_Ide_Types.Lookup (symbol, context, pos_opt, rq_info, symrange)) -> (run_lookup st symbol context pos_opt rq_info symrange)
    | (FStarC_Interactive_Ide_Types.Compute (term, rules)) -> (let tmp = (run_compute st term rules) in
      (as_json_list tmp))
    | (FStarC_Interactive_Ide_Types.Search (term)) -> (let tmp = (run_search st term) in
      (as_json_list tmp))
    | (FStarC_Interactive_Ide_Types.Callback (f)) -> (f st)
    | (FStarC_Interactive_Ide_Types.Format (code)) -> (let tmp = (run_format_code st code) in
      (as_json_list tmp))
    | FStarC_Interactive_Ide_Types.RestartSolver -> (((((st).FStarC_Interactive_Ide_Types.repl_env).FStarC_TypeChecker_Env.solver).FStarC_TypeChecker_Env.refresh None);
      ((FStarC_Interactive_Ide_Types.QueryOK, []), (FStar_Pervasives.Inl (st))))
    | (FStarC_Interactive_Ide_Types.Cancel (tmp)) -> ((FStarC_Interactive_Ide_Types.QueryOK, []), (FStar_Pervasives.Inl (st)))
  )

