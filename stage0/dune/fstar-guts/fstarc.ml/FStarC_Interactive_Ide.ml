let maybe_cancel_queries (st : FStarC_Interactive_Ide_Types.repl_state) (l : (FStarC_Interactive_Ide_Types.query) list) : ((FStarC_Interactive_Ide_Types.query) list * FStarC_Interactive_Ide_Types.repl_state) =
  (let log_cancellation = (fun l1 -> (let tmp = (!(dbg)) in
    (if tmp then (FStarC_List.iter (fun q -> (let tmp1 = (FStarC_Interactive_Ide_Types.query_to_string q) in
    (FStarC_Format.print1 "Cancelling query: %s\n" tmp1))) l1) else ()))) in
  (match (st).FStarC_Interactive_Ide_Types.repl_buffered_input_queries with
    | ({ FStarC_Interactive_Ide_Types.qq = (FStarC_Interactive_Ide_Types.Cancel (p)); qid = tmp; _ } :: rest) -> (let st1 = { FStarC_Interactive_Ide_Types.repl_line = (st).FStarC_Interactive_Ide_Types.repl_line;
          repl_column = (st).FStarC_Interactive_Ide_Types.repl_column;
          repl_fname = (st).FStarC_Interactive_Ide_Types.repl_fname;
          repl_deps_stack = (st).FStarC_Interactive_Ide_Types.repl_deps_stack;
          repl_curmod = (st).FStarC_Interactive_Ide_Types.repl_curmod;
          repl_env = (st).FStarC_Interactive_Ide_Types.repl_env;
          repl_stdin = (st).FStarC_Interactive_Ide_Types.repl_stdin;
          repl_names = (st).FStarC_Interactive_Ide_Types.repl_names;
          repl_buffered_input_queries = rest;
          repl_lang = (st).FStarC_Interactive_Ide_Types.repl_lang } in
      (match p with
        | None -> ((log_cancellation l);
          ([], st1))
        | (Some (p1)) -> (let query_ahead_of = (fun p2 q -> (match p2 with
              | (tmp1, l1, c) -> (match (q).FStarC_Interactive_Ide_Types.qq with
                  | (FStarC_Interactive_Ide_Types.Push (pq)) -> (Prims.op_Greater_Equals (pq).FStarC_Interactive_Ide_Types.push_line l1)
                  | tmp2 -> false
