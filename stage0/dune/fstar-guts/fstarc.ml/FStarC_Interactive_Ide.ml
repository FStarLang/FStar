      ))
    | tmp -> (l, st)
  ))

let rec fold_query (f : (FStarC_Interactive_Ide_Types.repl_state -> (FStarC_Interactive_Ide_Types.query -> ((FStarC_Interactive_Ide_Types.query_status * (FStarC_Json.json) list) * (FStarC_Interactive_Ide_Types.repl_state, Prims.int) FStar_Pervasives.either)))) (l : (FStarC_Interactive_Ide_Types.query) list) (st : FStarC_Interactive_Ide_Types.repl_state) : ((FStarC_Interactive_Ide_Types.query_status * (FStarC_Json.json) list) * (FStarC_Interactive_Ide_Types.repl_state, Prims.int) FStar_Pervasives.either) =
  (match l with
    | [] -> ((FStarC_Interactive_Ide_Types.QueryOK, []), (FStar_Pervasives.Inl (st)))
    | (q :: l1) -> (let tmp = (f st q) in
      (match tmp with
        | ((status, responses), st') -> ((FStarC_List.iter (write_response (q).FStarC_Interactive_Ide_Types.qid status) responses);
          (match (status, st') with
            | (FStarC_Interactive_Ide_Types.QueryOK, (FStar_Pervasives.Inl (st1))) -> (let st2 = (buffer_input_queries st1) in
              let tmp1 = (maybe_cancel_queries st2 l1) in
              (match tmp1 with
                | (l2, st3) -> (fold_query f l2 st3)
              ))
            | tmp1 -> ((status, []), st')
          ))
      ))
  )

