    | ((Some ((FStarC_Syntax_Syntax.Meta (t1)))), (Some ((FStarC_Syntax_Syntax.Meta (t2))))) -> (term_eq_dbg dbg t1 t2)
    | ((Some (FStarC_Syntax_Syntax.Equality)), (Some (FStarC_Syntax_Syntax.Equality))) -> true
    | tmp -> false
  )

