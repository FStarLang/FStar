            (check_term_eq dbg "branch body" tmp2)) else false) in
          (if tmp2 then (let tmp3 = (match (w1, w2) with
              | ((Some (x)), (Some (y))) -> (term_eq_dbg dbg x y)
              | (None, None) -> true
              | tmp3 -> false
            ) in
