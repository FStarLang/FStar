    | ((FStar_Pervasives.Inl (x1)), (FStar_Pervasives.Inl (y1))) -> (e1 x1 y1)
    | ((FStar_Pervasives.Inr (x1)), (FStar_Pervasives.Inr (y1))) -> (e2 x1 y1)
    | tmp -> false
  )

let rec bqual_eq_dbg (dbg : bool) (a1 : (FStarC_Syntax_Syntax.binder_qualifier) option) (a2 : (FStarC_Syntax_Syntax.binder_qualifier) option) : bool =
