and antiquotations_eq_dbg (dbg : bool) (a1 : ((FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax) list) (a2 : ((FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax) list) : bool =
