            | (FStarC_Syntax_Syntax.Tm_fvar (fv)) when (FStarC_Syntax_Syntax.fv_eq_lid fv FStarC_Parser_Const.unit_lid) -> (let tmp4 = (FStarC_Syntax_Subst.open_term ((FStarC_Syntax_Syntax.mk_binder b) :: []) p) in
