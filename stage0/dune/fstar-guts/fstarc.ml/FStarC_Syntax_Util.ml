  (if tmp2 then (let tmp3 = (eqlist (term_eq_dbg dbg) (b1).FStarC_Syntax_Syntax.binder_attrs (b2).FStarC_Syntax_Syntax.binder_attrs) in
  (check_term_eq dbg "binder attrs" tmp3)) else false))

