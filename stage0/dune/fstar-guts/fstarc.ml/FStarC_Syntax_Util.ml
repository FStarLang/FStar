and term_eq_dbg (dbg : bool) (t1 : (FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax) (t2 : (FStarC_Syntax_Syntax.term') FStarC_Syntax_Syntax.syntax) : bool =
  (let tmp = (unmeta_safe t1) in
  let t11 = (canon_app tmp) in
  let tmp1 = (unmeta_safe t2) in
  let t21 = (canon_app tmp1) in
  let check = (check_term_eq dbg) in
  let fail = (fail_term_eq dbg) in
  let t12 = (FStarC_Syntax_Subst.compress t11) in
  let t22 = (FStarC_Syntax_Subst.compress t21) in
  (match ((t12).FStarC_Syntax_Syntax.n, (t22).FStarC_Syntax_Syntax.n) with
    | ((FStarC_Syntax_Syntax.Tm_delayed (tmp2)), tmp3) -> (FStarC_Effect.failwith "term_eq: impossible, should have been removed")
    | (tmp2, (FStarC_Syntax_Syntax.Tm_delayed (tmp3))) -> (FStarC_Effect.failwith "term_eq: impossible, should have been removed")
    | ((FStarC_Syntax_Syntax.Tm_ascribed (tmp2)), tmp3) -> (FStarC_Effect.failwith "term_eq: impossible, should have been removed")
    | (tmp2, (FStarC_Syntax_Syntax.Tm_ascribed (tmp3))) -> (FStarC_Effect.failwith "term_eq: impossible, should have been removed")
    | ((FStarC_Syntax_Syntax.Tm_uinst (t13, us1)), (FStarC_Syntax_Syntax.Tm_uinst (t23, us2))) -> (let tmp2 = (eqlist eq_univs us1 us2) in
